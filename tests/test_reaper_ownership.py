pytest.importorskip("redislite")


@pytest.fixture(autouse=True)
def _stand_in_for_live_redis(monkeypatch):
    """A LIVE pgrep'd redis-server is simulated the way the guard READS it
    (#1642 FIX 5's pattern): our own pid is alive, and `_pid_is_redis` says
    it is a redis-server. MIN_UPTIME=0 disables the boot cooldown.
    """
    monkeypatch.setenv("TORTOISE_REAPER_MIN_UPTIME", "0")
    monkeypatch.setattr(R, "_pid_is_redis", lambda pid: pid == os.getpid())
    yield


@contextlib.contextmanager
def _short_base():
    """SHORT ephemeral base — macOS AF_UNIX sun_path is ~104 bytes, so
    pytest's tmp_path is too long for a real socket bind."""
    base = Path(tempfile.mkdtemp(prefix="tt_"))
    try:
        yield base
    finally:
        shutil.rmtree(base, ignore_errors=True)


def _socket_dir(base: Path, name: str) -> Path:
    d = base / name
    d.mkdir()
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.bind(str(d / "redis.socket"))
    s.close()  # a real (dead) socket file persists
    return d


def _instrument(d: Path, pid: int | None = None) -> None:
    """Write tortoise's per-server owner instrument (#3599), as
    `tortoise.FalkorDB`/`record_owner` does in production."""
    od = d / R.OWNERS_DIRNAME
    od.mkdir(exist_ok=True)
    (od / f"{pid if pid is not None else os.getpid()}-1").write_text("")


def _no_path_registry(d: Path, pid: int | None = None) -> None:
    """A redislite registry describing a no-path server rooted in its own
    tempdir (`dbfilename 'redis.db'`) — what a foreign redislite app writes.
    """
    (d / "redis.pid").write_text(f"{pid if pid is not None else os.getpid()}\n")
    (d / "redis.config").write_text(
        f"dbfilename 'redis.db'\ndir '{d}'\npidfile '{d}/redis.pid'\n")


def _no_path_registry_missing_data_dir(d: Path, gone: Path) -> None:
    """Same registry shape, but its `dir` names a path that no longer exists
    — the #4546 residue (`pytest` `tmp_path` teardown removed the data dir
    while the socket dir survived). `dir_missing` is derived from THIS field.
    """
    (d / "redis.pid").write_text(f"{os.getpid()}\n")
    (d / "redis.config").write_text(
        f"dbfilename 'redis.db'\ndir '{gone}'\npidfile '{d}/redis.pid'\n")


# ── #4496: the probes must not raise when `subprocess.run` is mocked ─────────

def test_probless_ps_stdout_is_undeterminable_not_raising(monkeypatch, tmp_path):
    """#4496: a non-text `ps` stdout reads as "undeterminable", never raises.

    Every probe in `embedded_reaper` is documented fail-CLOSED — `None` (or
    an empty result) means "cannot tell" — yet each parses captured
    `ps`/`lsof`/`pgrep` stdout with `.strip()` / `.splitlines()` /
    `re.match`. Dozens of tests fake git detection with
    `mock.patch("subprocess.run")`, whose `stdout` is a MagicMock; the read
    then raised `TypeError` out of a helper whose contract is "or None".

    That was a LEAK, not a crash. The exception propagated through
    `_owner_records` into `cotenant_holds_server`, whose deliberate
    fail-closed `except Exception: return True` then reported a PHANTOM
    co-tenant — so the LAST of two clients on one embedded daemon declined
    the shutdown and the daemon survived uninstrumented with its directory
    present. That is exactly the
    `candidate / path_based=False / unattributed=True / dir_missing=False`
    survivor `test-slow (b)` reports (threshold 0) and #3767 deliberately
    refuses to fast-kill.

    `_owner_records` must also stay total: it is the discriminator the whole
    ownership claim reads, and a raise there is what flipped the close.
    """
    from unittest import mock

    d = tmp_path / "mock-ps"
    owners = d / R.OWNERS_DIRNAME
    owners.mkdir(parents=True)
    # start=1 is a REAL float, which is what makes `_owner_records` consult
    # `ps` at all (an 'unknown' stamp short-circuits to the pid-liveness
    # arm and never reaches the parser — hence the ordering-dependent leak).
    (owners / f"{os.getpid()}-1").write_text("")
    sp = str(d / R.SOCKET_MARKER)

    # Force the single-`ps` fallback: the per-sweep cache would otherwise
    # answer for our own pid. (`delitem`, not an empty record — the cache is
    # fully populated by `_batch_process_info`, so a partial entry is not a
    # shape the probes promise to read.)
    monkeypatch.delitem(R._PROC_INFO_CACHE, os.getpid(), raising=False)

    with mock.patch("subprocess.run") as fake:
        fake.return_value.returncode = 0  # a fake git probe that "succeeds"
        assert R._process_start_time(os.getpid()) is None
        # The owner is still OURS and alive — the undeterminable start must
        # not be read as "no live owner" (that would licence a kill).
        assert R._owner_records(sp) == (1, 1)


def test_uptime_and_cmdline_also_tolerate_a_mock(monkeypatch, tmp_path):
    """The same guard covers the sibling captured-stdout readers.

    `_process_start_time` was the one on the close path (pinned in the test
    above), but the module has eight other readers that parse captured
    `ps`/`lsof`/`pgrep`/`redis-cli` stdout, and only one of the whole set
    raises on a MagicMock (`_parse_lstart`). The rest fail *silently*, which
    is worse — the value they hand back is wrong:

    * `_cmdline` returns the mock itself;
    * `_is_detached` -> `int(MagicMock()) == 1` and `1 in (0, 1)` is **True**,
      i.e. the strongest orphan signal, from an unreadable `ps`;
    * `_client_list`/`_active_client_count` -> `_parse_client_list(MagicMock())`
      is `[]`, the "zero clients" verdict that licences a kill;
    * `_uptime_seconds` -> `_parse_etime(MagicMock())` is `0.0`, the
      *youngest* possible uptime — a wrong value that lands on the SAFE side
      of `_cooldown_check`'s `uptime < min_uptime`. The guard now yields
      `None`, which `_cooldown_check` reads as "not protected by the boot
      cooldown" (the permissive side) — DELIBERATE and pre-existing, not a
      fail-open introduced here: a real `ps` timeout/OSError already produced
      `None` on this path before the guard, and treating a failed probe as
      protected would make the reaper inert whenever `ps` is slow or absent
      (#3599). The safety gates are `reap()`'s owner-record / held-flock /
      orphan-confirmation checks, not this classification — see
      `_cooldown_check`'s comment.

    Deliberately NOT asserted: `_process_has_socket`, `_derive_real_pid_macos`,
    `_pgrep_redis_servers` and `_batch_process_info`. A MagicMock happens to
    yield their safe value already (`"p<pid>" in MagicMock()` is False, and
    iterating `MagicMock().splitlines()` yields nothing), so asserting them
    would pin the contract value while proving nothing about the guard — the
    kind of assertion that reads as coverage and is not.
    """
    from unittest import mock

    monkeypatch.delitem(R._PROC_INFO_CACHE, os.getpid(), raising=False)
    with mock.patch("subprocess.run") as fake:
        fake.return_value.returncode = 0
        assert R._uptime_seconds(os.getpid()) is None  # pre-guard: 0.0
        assert R._cmdline(os.getpid()) == ""  # pre-guard: the mock itself
        assert R._is_detached(os.getpid()) is False  # pre-guard: True
        # `returncode == 0` is redis-cli's own success word, so a non-text
        # stdout must not be parsed as "zero clients" — None is the
        # caller-safe "client state unknown".
        assert R._client_list(str(tmp_path / "nope.sock")) is None
        assert R._active_client_count(str(tmp_path / "nope.sock")) is None


# ── NEGATIVE CONTROL — an unowned dir is NOT ours ────────────────────────────

def test_registryless_unowned_dir_is_not_a_candidate():
    """Acceptance 1 (RED on the unfixed code): an UNOWNED autogenerated-tempdir
    dir with no `.db` file must NOT be admitted as a candidate.

    Pre-fix, `_classify`'s registry-is-None branch fell through to
    `_cooldown_check` on the name/containment heuristic and returned
    'candidate'. Restore `return _cooldown_check(registry, pid=pid)` there and
    this test fails with `assert 'candidate' == 'protected'`.
    """
    with _short_base() as base:
        d = _socket_dir(base, "tmpUNOWNED")  # matches _AUTOGEN_DIRNAME
        # No redis.config / *.settings (registry is None) and NO
        # `.tortoise-owners` instrument: nothing claims this dir as tortoise's.
        assert not (d / R.OWNERS_DIRNAME).exists()
        assert R._classify(str(d / "redis.socket"), os.path.realpath(str(d)),
                           os.path.realpath(str(base)), None,
                           pid=os.getpid()) == "protected"


def test_registryless_unowned_dir_is_not_reaped(monkeypatch):
    """Acceptance 1/2 — the unowned dir is not a candidate and reap() does
    not act on it even in a FULL sweep (`only_safe=False`)."""
    with _short_base() as base:
        d = _socket_dir(base, "tmpUNOWNED")
        rec = R._classify_dir(str(d), str(d / "redis.socket"),
                              known_pid=os.getpid())
        assert rec is not None
        assert rec["classification"] == "protected", rec["classification"]
        assert rec["unattributed"] is True
        killed: list[int] = []
        monkeypatch.setattr(R, "_kill",
                            lambda pid, timeout: killed.append(pid))
        acted = R.reap([dict(rec)], dry_run=False, only_safe=False)
        assert acted == []
        assert killed == [], "an unowned dir must never be reaped"


def test_unattributed_no_path_server_is_not_fast_killed(monkeypatch):
    """Acceptance 1 (the DOMINANT cross-owner route): a foreign no-path
    redislite server with an INTACT registry is admitted as a candidate —
    redislite's registry is written by redislite, not tortoise, so it is not
    an ownership claim — but it has no `.tortoise-owners` instrument, so it
    must NOT be fast-killed without the #1557/#1642 FIX 3 orphan
    confirmation, in EVERY mode. Pre-fix this was killed by any full sweep
    (`path_based=False`, `unattributed` did not exist)."""
    with _short_base() as base:
        d = _socket_dir(base, "tmpFOREIGN")
        _no_path_registry(d)
        rec = R._classify_dir(str(d), str(d / "redis.socket"),
                              known_pid=os.getpid())
        assert rec is not None
        assert rec["classification"] == "candidate"
        assert rec["path_based"] is False  # registry says no-path...
        assert rec["unattributed"] is True  # ...but nothing claims it as OURS
        # #4546 mutation guard: this is the DIR-PRESENT class (#3767's
        # target). Its `dir_missing` is False, so the #4546 exemption must NOT
        # reach it — widening the exemption beyond `dir_missing` REDs here.
        assert rec["dir_missing"] is False
        killed: list[int] = []
        monkeypatch.setattr(R, "_kill",
                            lambda pid, timeout: killed.append(pid))
        monkeypatch.setattr(R, "_active_client_count", lambda _s: 0)
        # Unconfirmed: skipped even in a full sweep (the pre-fix kill path).
        assert R.reap([dict(rec)], dry_run=False, only_safe=False) == []
        assert killed == []
        # Confirmed orphan: still killed — the change is not inertness.
        confirmed = dict(rec, _orphan_confirmed=True)
        R.reap([confirmed], dry_run=False, only_safe=False)
        assert killed == [os.getpid()], killed


def test_is_path_based_fails_closed_without_a_registry():
    """The issue's compounding point: `_is_path_based` used to `return False`
    when the registry was absent, so a registry-less record reported
    `path_based=False` and the strongest protection never engaged. Without a
    registry there is no signal to read, so it must fail CLOSED."""
    with _short_base() as base:
        d = _socket_dir(base, "tmpNOREG")
        assert R._is_path_based(None, os.path.realpath(str(d)),
                                os.path.realpath(str(base))) is True


def test_absent_registryless_dir_needs_the_live_pids_own_argv(monkeypatch):
    """The ownership claim's ABSENT-dir arm (#1005 / #1642 FIX 3 pass-1
    binding), both directions. A registry-less dir that is absent is admitted
    ONLY when the LIVE pid's own argv names it — the one binding a foreign
    uid cannot author (it cannot edit another process's command line). With
    no such binding it is refused. Neither arm was covered before."""
    with _short_base() as base:
        absent = os.path.realpath(str(base / "tmpABSENT"))
        assert not os.path.exists(absent)
        # Bound to the live pid's own argv -> admitted.
        monkeypatch.setattr(R, "_pid_cmdline_names_dir",
                            lambda pid, dbdir: dbdir == absent)
        assert R._has_ownership_claim(absent, os.getpid()) is None
        # No binding -> refused (fail closed).
        monkeypatch.setattr(R, "_pid_cmdline_names_dir",
                            lambda pid, dbdir: False)
        refusal = R._has_ownership_claim(absent, os.getpid())
        assert refusal is not None and "absent" in refusal, refusal


def _load_embedded_orphans():
    """Import tools/embedded_orphans.py by path (it is a CLI, not a module)."""
    import importlib.util
    root = Path(__file__).resolve().parent.parent
    spec = importlib.util.spec_from_file_location(
        "embedded_orphans_3767", root / "tools" / "embedded_orphans.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_census_keeps_socketless_orphans_in_the_orphan_bucket(monkeypatch):
    """#3767 review P1 (regression): a socket-dir-MISSING server is attributed
    by the live pid's OWN argv — the same arm the reaper admits it by — and
    `_owner_record_dir_present` necessarily reads False for it. It must keep
    its `socket-dir-missing` orphan bucket; bucketing it `unattributed` would
    move the whole #1005 socketless leak class out of `orphans` and out of the
    census exit code, i.e. exit 0 while the leak grows."""
    mod = _load_embedded_orphans()
    sock_dir = "/tmp/3767-does-not-exist/tmpX"
    monkeypatch.setattr(mod, "_enumerate_servers_strict", lambda: [os.getpid()])
    # census() imports these from tortoise.embedded_reaper at call time, so
    # they are patched on THAT module, not on the CLI module.
    monkeypatch.setattr(R, "_socket_dir_from_cmdline", lambda pid: sock_dir)
    monkeypatch.setattr(
        R, "_classify_dir",
        lambda d, s, known_pid=None: {"classification": "candidate",
                                      "unattributed": True,
                                      "path_based": False})
    monkeypatch.setattr(R, "_owner_records", lambda s: None)
    monkeypatch.setattr(R, "_socket_dir_missing", lambda s: True)
    res = mod.census()
    assert res["unattributed"] == 0, res
    assert res["orphans"] == 1, res
    assert res["orphan_details"][0]["reason"] == "socket-dir-missing", res


