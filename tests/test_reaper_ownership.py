"""#3767 — the reaper's OWNERSHIP CLAIM (containment is not ownership).

`embedded_reaper.py` admitted, as a kill **candidate**, any autogenerated-named
/ tempdir-contained socket dir with no `.db` file. Name and containment are
evidence ANY co-resident redislite application produces, so a server belonging
to another same-uid app, a second tortoise instance, or another tenant sharing
TMPDIR was reachable and reapable — an isolation defect (a more active reaper
scales the kill, which is why #3767 gates #4299).

This module pins the fix in BOTH directions:

  NEGATIVE (acceptance 1/2) — an UNOWNED registry-less dir is `protected`, not
    a candidate, and is not reaped; and an UNATTRIBUTABLE (registry-present but
    no `.tortoise-owners` instrument) no-path server is not fast-killed without
    orphan confirmation.
  POSITIVE (acceptance 3) — our OWN residue is still reaped: an instrumented
    server is still fast-killed, the #1642 FIX 2 dead-pid leftover still
    classifies `stale_socket`, and the #1005 `dir_missing` server is still
    admitted. The reaper is NOT made inert.

The claim itself (`_has_ownership_claim`) is: a PRESENT dir must be owned by
the invoking euid (#4136's property, moved to admission) AND carry tortoise's
own `.tortoise-owners` instrument (#3599); a dir-ABSENT server is admitted by
the live pid's own argv naming it (#1642 FIX 3's pass-1 binding, #4136's
unforgeable arm). The #1557 confirmation window is untouched.

#4546 (OVERRIDES #3767 for the `dir_missing` class ONLY): in a FULL sweep
(`only_safe=False`) `reap()`'s `unattributed` arm exempts a `dir_missing`
record — a LIVE server whose REGISTRY data dir (the pytest `tmp_path` tree) is
already gone, so no on-disk user data remains and pre-#3767 `main` fast-killed
it. (#3767's every-mode `unattributed` requirement CARRIES #1642 FIX 3's "a
missing dir keeps the confirmation window" stance; that carried stance is what
the exemption relaxes, for this class ONLY — #1642 FIX 3's socket-dir-unlinked
window and the `path_based` arm are NOT touched.) The exemption is exactly
that property: `test_dir_missing_unattributed_residue_is_still_fast_killed`
(positive) and `test_unattributed_no_path_server_is_not_fast_killed` (the
dir-PRESENT negative control) are two of its mutation guards, and
`test_path_based_dir_missing_server_is_not_fast_killed` pins the untouched
`path_based` arm. Under `--only-safe` the exemption is unreachable (the
earlier live-pid gate skips first), so `--only-safe` is unchanged.
"""
