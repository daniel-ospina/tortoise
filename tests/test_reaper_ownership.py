def test_path_based_dir_missing_server_is_not_fast_killed(monkeypatch):
    """#4546 hard constraint: the exemption is scoped to the NEW
    `unattributed` arm. A genuinely PATH-BASED (user-data) server whose
    registry data dir is gone is still gated by the UNTOUCHED `path_based`
    arm — it is not fast-killed in a full sweep, because its data outlives
    the test tree and #1642 FIX 3's confirmation window applies in EVERY mode.

    RED if the exemption is widened to `(path_based and not dir_missing) or
    (unattributed and not dir_missing)` — that mutation lets a `dir_missing`
    user-data server through, which is exactly what the #4546 scoping
    forbids. The socket dir is PRESENT here (registry data dir is the missing
    one).
    """
    with _short_base() as base:
        d = _socket_dir(base, "tmpUSRDATA")   # socket dir PRESENT
        gone = Path("/nonexistent-4546-user-data")  # non-ephemeral user path
        assert not gone.exists()
        (d / "redis.pid").write_text(f"{os.getpid()}\n")
        (d / "redis.config").write_text(
            f"dbfilename 'redis.db'\ndir '{gone}'\npidfile '{d}/redis.pid'\n")
        rec = R._classify_dir(str(d), str(d / "redis.socket"),
                              known_pid=os.getpid())
        assert rec is not None
        assert rec["classification"] == "candidate"
        assert rec["path_based"] is True    # registry 'dir' is a USER path
        assert rec["dir_missing"] is True   # ...and it is gone
        killed: list[int] = []
        monkeypatch.setattr(R, "_kill",
                            lambda pid, timeout: killed.append(pid))
        monkeypatch.setattr(R, "_active_client_count", lambda _s: 0)
        acted = R.reap([dict(rec)], dry_run=False, only_safe=False)
        assert acted == []
        assert killed == [], "a path_based server must keep the gate"


# ── #4577 × #3767: LIVENESS is not ADMISSION ────────────────────────────────

def test_owner_lock_file_alone_is_not_an_ownership_claim(tmp_path):
    """#4577 × #3767 reconciliation: a HELD owner lock is a LIVENESS signal,
    not an admission claim.

    `OWNER_LOCK_NAME` (main `845f47f53`, #4577) lives inside
    `OWNERS_DIRNAME`, so the flock change dropped a new file into the very
    directory #3767's claim reads. If the claim counted it, the lock would
    SILENTLY widen the admission gate — a lock arm would admit a dir whose
    only tortoise marker is a `.lock` a same-uid foreign app can plant and
    flock itself.

    It need not be an admission claim: main's `reap()` already vetoes
    `_owner_lock_held(...) is True` at DESTRUCTION, which is where a liveness
    fact belongs (a dir admitted on a lock arm would be skipped by that very
    check, so the arm could never produce a kill). This test pins the
    separation: a `.tortoise-owners` dir holding only `.lock` carries NO
    claim and `_has_ownership_claim` REFUSES it.

    RED if the lock arm is added to the claim (e.g. `if _owner_lock_held(...)
    is True: return None`) — that is the mutation this pins.
    NOT pinned here: the dotted-name skip in `_owner_record_dir_present`. A
    dotted name could never pass the positive-pid parse anyway
    (`int(".lock".partition("-")[0])` raises ValueError), so the skip is
    intent-documenting rather than load-bearing, and no test can
    mutation-verify it.
    """
    import fcntl

    d = tmp_path / "tmpLOCKONLY"
    d.mkdir()
    od = d / R.OWNERS_DIRNAME
    od.mkdir()
    lock = od / R.OWNER_LOCK_NAME
    lock.write_text("")
    fd = os.open(str(lock), os.O_RDWR)
    try:
        fcntl.flock(fd, fcntl.LOCK_SH)   # a "live owner" holds it
        sock = str(d / "redis.socket")
        assert R._owner_lock_held(sock) is True, (
            "precondition: the held shared lock must read as a live owner")
        assert R._owner_record_dir_present(str(d)) is False, (
            "the `.lock` file alone must not satisfy the ownership claim")
        refusal = R._has_ownership_claim(str(d), os.getpid())
        assert refusal is not None and R.OWNERS_DIRNAME in refusal, refusal
    finally:
        os.close(fd)
