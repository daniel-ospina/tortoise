# ════════════════════════════════════════════════════════════════════════════
# 1. THE SEAM EMITS THE RECORD'S PLAN — exactly, and nothing of its own
# ════════════════════════════════════════════════════════════════════════════


def test_the_seam_emits_exactly_the_record_plan() -> None:
    """`replay_plan` is the ONE declaration of journal→record; the seam adds none.

    An extra statement here is a second fold; a missing one is a record the
    boundary silently drops. The assertion is equality over the WHOLE set — the
    tenant prologue first (R6), then the plan, nothing else. (The seam's second
    context statement, the ``TENANT_SCOPE_SQL`` verify, is absent from
    ``statements()`` by the ``current_setting`` filter, not by omission.)
    """
    conn = FakeConnection()
    result = _armed(conn).write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert conn.statements() == _executed()
    assert result.events == len(RECORDS)
    # `statements` counts RECORD mutations (the projection's own definition:
    # every executed statement that is not a journal-position write). Derived
    # from the connection's log, not from the plan, so the count is pinned
    # independently of the number it is compared against. The tenant prologue
    # is not a record mutation, so it is subtracted — exactly one of it.
    assert conn.statements().count(_tenant_statement()) == 1
    # The context statements are outside the plan: the tenant prologue AND its
    # read-back (#9600 review cycle 1 — `replay()` verifies the GUC took effect).
    _context = 2
    assert result.statements == (
        len(conn.executed) - len(conn.journal_positions) - _context)
    assert result.statements > 0
    # The plan is one journal position per record, always.
    assert len(conn.journal_positions) == len(RECORDS)


def test_every_executed_statement_is_the_tenant_or_the_plan_in_order() -> None:
    """No statement the seam invented beyond the prologue, none reordered."""
    conn = FakeConnection()
    _armed(conn).write(RECORDS, org_id=ORG, graph_id=GRAPH)
    expected = [sql for sql, _ in _executed()]
    assert [sql for sql, _ in conn.statements()] == expected
    # …and the prologue is FIRST, before anything the plan would scope.
    assert conn.statements()[0][0] == rp.TENANT_GUC_SQL


# ════════════════════════════════════════════════════════════════════════════
# 2. IDEMPOTENCE — the same records twice
# ════════════════════════════════════════════════════════════════════════════


def test_replaying_twice_emits_the_same_statements() -> None:
    conn = FakeConnection()
    writer = _armed(conn)
    writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)
    first = conn.statements()
    writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)
    second = conn.statements()[len(first):]
    assert second == first


def test_a_second_replay_adds_no_journal_event_for_an_applied_position() -> None:
    """`#5285`'s rule, moved to the record: replay twice, compare the record.

    The second run EMITS the position insert (the plan is deterministic) and the
    record absorbs it — no duplicate `journal_event` row for a position already
    consumed. Both halves are asserted: emitting nothing would mean the plan had
    changed, and a duplicate row would mean the key had.
    """
    conn = FakeConnection()
    writer = _armed(conn)
    writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)
    positions_after_first = set(conn.journal_positions)
    rows_after_first = len(conn.executed)

    writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert set(conn.journal_positions) == positions_after_first
    second_run = [p for sql, p in conn.executed[rows_after_first:]
                  if sql.startswith(rp._JOURNAL_INSERT_PREFIX)]
    assert {(p[0], p[1], p[2]) for p in second_run} == positions_after_first
    assert set(conn.absorbed) == positions_after_first


