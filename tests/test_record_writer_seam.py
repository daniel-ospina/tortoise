# 4. UNARMED IS NAMED — never a silent no-op, never an exception
# ════════════════════════════════════════════════════════════════════════════


def test_not_armed_returns_a_named_outcome_and_touches_nothing() -> None:
    """The default deployment: zero statements, zero connections, no exception.

    §2.0 requires capture to be byte-identical for a deployment that has not
    armed the record, so the seam must not even materialize the plan.
    """
    opened: list[str] = []
    writer = rw.RecordWriter(connect=lambda dsn: opened.append(dsn))

    result = writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert result.outcome is rw.RecordWriteOutcome.NOT_ARMED
    assert result.applied is False
    assert result.events == 0 and result.statements == 0
    assert result.connection is None
    assert opened == []


def test_a_not_armed_call_reports_the_position_it_did_NOT_consume() -> None:
    """`last_seq` is `first_seq - 1` when nothing was written — never `0`.

    The production shape (#9188) is a caller mid-journal: `first_seq=41` with an
    unarmed record. A `last_seq` of 0 there makes `next_offset = last_seq + 1`
    rewind the caller's watermark to journal position 1 — re-consuming positions
    it had already recorded, which is the renumbering decision 5 forbids.
    The dataclass default hid this for the only offset any test used.
    """
    result = rw.RecordWriter().write(RECORDS, org_id=ORG, graph_id=GRAPH,
                                     first_seq=41)

    assert result.outcome is rw.RecordWriteOutcome.NOT_ARMED
    assert (result.first_seq, result.last_seq) == (41, 40)
    assert result.last_seq + 1 == result.first_seq     # no rewind, no skip


def test_not_armed_is_distinguishable_from_success_and_carries_the_recorded_term() -> None:
    """The caller can tell it apart, and the word is the RECORDED one.

    `not-armed` is a *seam* outcome name; the status word a client-facing
    surface reads is `status_vocabulary`'s `unconfigured` — "off by policy".
    This asserts the two agree with the recorded classifier rather than being
    restated, so the write side cannot drift from the read side.
    """
    unarmed = rw.RecordWriter().write(RECORDS, org_id=ORG, graph_id=GRAPH)
    armed = _armed().write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert unarmed.status == status_vocabulary.STATUS_UNCONFIGURED
    assert unarmed.status == status_vocabulary.classify(configured=False,
                                                       reached=False)
    assert armed.status == status_vocabulary.STATUS_AVAILABLE
    assert armed.applied is True and unarmed.applied is False
    # No fifth term was minted by the seam.
    assert unarmed.status in status_vocabulary.CLIENT_STATUS_TERMS
    assert armed.status in status_vocabulary.CLIENT_STATUS_TERMS


def test_an_unarmed_seam_does_not_fail_a_capture_over_a_poison_record() -> None:
    """Unarmed must not pay the fold: a type it is not writing cannot fail it."""
    result = rw.RecordWriter().write(
        [{"type": "SomethingNobodyDeclared", "ts": "T", "id": "x"}],
        org_id=ORG, graph_id=GRAPH,
    )
    assert result.outcome is rw.RecordWriteOutcome.NOT_ARMED


def test_a_blank_dsn_is_unarmed_not_malformed() -> None:
    """Unset and blank are the same statement: nothing was declared."""
    assert rw.record_dsn("") is None
    assert rw.record_dsn("   ") is None
    assert rw.RecordWriter(dsn="   ").armed is False


def test_the_dsn_is_resolved_per_call_so_a_late_arming_is_seen(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A process started before the record was armed picks it up (#9187 dec. 2)."""
    writer = rw.RecordWriter(connect=lambda _dsn: FakeConnection())
    assert writer.armed is False

    monkeypatch.setenv(rw.RECORD_DSN_ENV, "postgresql://record/db")
    assert writer.armed is True
    assert writer.write(RECORDS, org_id=ORG, graph_id=GRAPH).applied is True


def test_a_malformed_dsn_raises_and_never_reads_as_unarmed() -> None:
    """A typo must not be silently 'not configured' — and must not leak itself."""
    secret = "mysql://user:hunter2@host/db"
    with pytest.raises(rw.RecordWriteError) as excinfo:
        rw.RecordWriter(dsn=secret).write(RECORDS, org_id=ORG, graph_id=GRAPH)

    message = str(excinfo.value)
    assert "hunter2" not in message
    assert "postgresql://" in message          # the fix is named
    assert "mysql://user" not in message


