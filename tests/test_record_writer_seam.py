# 5. THE SEAM OWNS NO TRANSACTION
# ════════════════════════════════════════════════════════════════════════════


def test_the_seam_never_commits_or_rolls_back() -> None:
    """§3 point 8: a `commit()` here would commit the projection ALONE.

    One transaction spans the journal append (the chokepoint) and this
    projection, so only the caller can own the boundary. Asserted on a
    connection the seam OPENED as well as one that was injected — the hook is
    the same, and a helper that committed "because it opened the connection" is
    exactly the dual write §3 forbids.
    """
    opened = FakeConnection()
    _armed(opened).write(RECORDS, org_id=ORG, graph_id=GRAPH)
    assert (opened.commits, opened.rollbacks) == (0, 0)

    injected = FakeConnection()
    _armed().write(RECORDS, org_id=ORG, graph_id=GRAPH, conn=injected)
    assert (injected.commits, injected.rollbacks) == (0, 0)


def test_an_injected_connection_is_the_callers_to_close() -> None:
    """The seam neither closes nor returns a connection it did not open."""
    injected = FakeConnection()
    result = _armed().write(RECORDS, org_id=ORG, graph_id=GRAPH, conn=injected)
    assert result.connection is None
    assert injected.closed == 0
    assert injected.statements() == _executed()


def test_a_seam_opened_connection_is_handed_back_for_the_caller_to_commit() -> None:
    """The seam resolves the connection; the caller still owns the boundary."""
    conn = FakeConnection()
    result = _armed(conn).write(RECORDS, org_id=ORG, graph_id=GRAPH)
    assert result.connection is conn
    assert conn.commits == 0                   # handed back UNcommitted
    assert conn.closed == 0


