def test_an_undeclared_record_type_raises_and_executes_no_statement() -> None:
    """A record type with no declared mutation fails the write, untouched.

    The seam wraps every armed-path failure in ONE catchable class so a caller
    has one thing to roll back on; `__cause__` keeps the projection's own type,
    so "totality refused this" stays machine-checkable.
    """
    conn = FakeConnection()
    poison = [{"type": "SomethingNobodyDeclared", "ts": "T", "id": "x"}]

    with pytest.raises(rw.RecordWriteError) as excinfo:
        _armed(conn).write(poison, org_id=ORG, graph_id=GRAPH)

    assert isinstance(excinfo.value.__cause__, rp.UnknownJournalRecordType)
    assert conn.statements() == []
    assert conn.commits == 0 and conn.rollbacks == 0


def test_a_refused_operation_raises_and_executes_no_statement() -> None:
    """A DECLARED refusal is a failure, not a skip — through the seam too."""
    conn = FakeConnection()
    refused = [{"type": "PointsMerged", "ts": "T", "op": "merge",
                "keep_id": "p1", "merge_ids": ["p2"]}]

    with pytest.raises(rw.RecordWriteError) as excinfo:
        _armed(conn).write(refused, org_id=ORG, graph_id=GRAPH)

    assert isinstance(excinfo.value.__cause__, rp.RefusedJournalOperation)
    assert conn.statements() == []


def test_a_partial_batch_is_all_or_nothing() -> None:
    """One poison record in the middle of a good batch executes nothing."""
    conn = FakeConnection()
    batch = [*RECORDS[:2], {"type": "SomethingNobodyDeclared", "ts": "T", "id": "x"}]
    with pytest.raises(rw.RecordWriteError):
        _armed(conn).write(batch, org_id=ORG, graph_id=GRAPH)
    assert conn.statements() == []


