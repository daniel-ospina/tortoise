"""The record-write seam's contract, made executable (#9187, epic #7879).

WHAT THIS PINS. #9187's indicators are four claims about the boundary between the
journal and the Postgres record, and each one is a test here rather than a
sentence in a design doc:

1. **The seam emits the record's plan — and nothing of its own.** For a fixed
   record set the executed statement set equals the tenant prologue
   (``record_projection.TENANT_GUC_SQL``, one statement, R6) followed by
   ``record_projection.replay_plan(records, …)``. That equality is also the
   duplication pin: a second, hand-written Postgres writer would drift from the
   fold, and it would show up here as an extra or missing statement. The seam
   issues TWO statements outside the plan — the prologue, and the
   ``TENANT_SCOPE_SQL`` verify that reads the GUC back and the connecting role's
   posture; ``FakeConnection.statements()`` filters the latter because it is a
   ``current_setting`` query, while ``executed`` holds both (hence ``_context =
   2`` in the count assertion). The prologue is named rather than tolerated, and
   it is the reason RLS can be the record's tenancy boundary at all (see
   ``test_record_tenancy_guc.py`` for its own pins).
2. **Idempotent.** Replaying the same records twice emits the same statement
   set, and the second run adds no ``journal_event`` row for an already-applied
   position (``#5285``'s rule, moved to the record).
3. **Totality survives the seam.** An undeclared record type raises and **zero**
   statements were executed.
4. **Unarmed is NAMED.** No DSN ⇒ ``NOT_ARMED`` returned, zero statements, no
   connection attempt, no exception — and the caller can tell it apart from
   success (`.applied`) and from failure (a failure raises).

Plus the three properties the epic's own decisions impose: the seam **never
commits or rolls back** (§3 point 8 — the caller owns the transaction); a
**configured-but-unreachable** record FAILS rather than reading as unarmed
(the recorded ``degraded``/``unconfigured`` split, on the write side); and the
**tenant pair is the CALLER's, never the process's** (#9192 ask 3) — two
tenants through this seam never cross-write, and the environment cannot stand
in for a pair the caller supplied.

NO DATABASE, NO DRIVER. Every connection here is a fake DB-API object that
records what it was asked to execute — the same shape
``record_projection.replay`` requires (``conn.cursor()`` →
``cursor.execute(sql, params)``), so this file runs in every Python lane and the
live-engine half stays where it belongs (#9188).
"""

