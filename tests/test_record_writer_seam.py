class FakeCursor:
    """Executes nothing; records everything, and honours `ON CONFLICT DO NOTHING`."""

    def __init__(self, conn: FakeConnection) -> None:
        self._conn = conn

    def fetchone(self) -> tuple[Any, ...]:
        # `replay()` reads the tenant GUC back after setting it (#9600 review
        # cycle 1) AND, on the same statement, the connecting role's posture
        # (#9600 review cycle 2). This fake is a connection that KEEPS its
        # transaction-local set and runs as the decision's NON-BYPASS role, so
        # both answers mirror what the reconnect would really see.
        if self._conn.last_sql == rp.TENANT_SCOPE_SQL:
            return (self._conn.guc_set, False)
        return (self._conn.guc_set,)

    def execute(self, sql: str, params: Any = None) -> None:
        values = list(params) if params is not None else None
        self._conn.executed.append((sql, values))
        self._conn.last_sql = sql
        if sql == rp.TENANT_GUC_SQL:
            self._conn.guc_set = params[0] if params else None
        if not sql.startswith(rp._JOURNAL_INSERT_PREFIX):
            return
        # The real table is append-only by TRIGGER and keyed on
        # `(org_id, graph_id, seq)`; `ON CONFLICT … DO NOTHING` is what makes a
        # second replay of the same position a no-op. Model exactly that, so
        # "no duplicate row for an applied position" is a real assertion.
        assert values is not None
        key = (values[0], values[1], values[2])
        if key in self._conn.journal_positions:
            self._conn.absorbed.append(key)
            return
        self._conn.journal_positions.add(key)


class FakeConnection:
    """A recording DB-API connection that forbids nothing but remembers all.

    `commits`/`rollbacks` are counted rather than raised so a test can assert
    "the seam never called it" — raising would be swallowed by the seam's own
    failure wrapper and the assertion would become untestable.
    """

    def __init__(self) -> None:
        self.executed: list[tuple[str, list[Any] | None]] = []
        self.guc_set: Any = None
        self.last_sql: str | None = None
        self.journal_positions: set[tuple[Any, Any, Any]] = set()
        self.absorbed: list[tuple[Any, Any, Any]] = []
        self.commits = 0
        self.rollbacks = 0
        self.closed = 0

    # — the DB-API surface `record_projection.replay` uses —
    def cursor(self) -> FakeCursor:
        return FakeCursor(self)

    def commit(self) -> None:
        self.commits += 1

    def rollback(self) -> None:
        self.rollbacks += 1

    def close(self) -> None:
        self.closed += 1

    # — assertions' helpers —
    def statements(self) -> list[tuple[str, list[Any] | None]]:
        # The tenant prologue and its read-back are CONTEXT, not the plan: the
        # plan comparisons below are equality over the plan, so the read-back
        # (`SELECT current_setting(...)`, #9600 review cycle 1) is filtered here
        # rather than pinned into every expected list. Its presence and order
        # are asserted separately.
        # Filtered by IDENTITY, not by substring: a substring filter would
        # also hide any hand-written statement that happened to mention
        # `current_setting`, which is the drift this equality exists to catch
        # (#9600 review cycle 5, P3).
        return [r for r in self.executed if r[0] != rp.TENANT_SCOPE_SQL]


def _plan(records: list[dict[str, Any]] | None = None, *,
          first_seq: int = 1) -> list[tuple[str, list[Any]]]:
    """The contract's own statement set, as ``(sql, params)`` pairs."""
    return [(s.sql, list(s.params)) for s in rp.replay_plan(
        RECORDS if records is None else records,
        org_id=ORG, graph_id=GRAPH, start_seq=first_seq,
    )]


def _tenant_statement(org: str = ORG) -> tuple[str, list[Any]]:
    """The seam's PROLOGUE — the first of its two statements outside the plan.

    The second is ``TENANT_SCOPE_SQL`` (the read-back plus the role posture),
    which ``FakeConnection.statements()`` filters out as a ``current_setting``
    query while ``executed`` keeps it.

    Named rather than filtered out of the log, so "the seam adds exactly these
    statements of its own, and the first is the tenant" is the assertion instead
    of "the seam's statements minus whatever it happens to add".
    """
    return (rp.TENANT_GUC_SQL, [org])


def _executed(records: list[dict[str, Any]] | None = None, *,
              first_seq: int = 1, org: str = ORG) -> list[tuple[str, list[Any]]]:
    """What a write must execute, in order: the tenant, then the plan."""
    return [*[_tenant_statement(org)], *_plan(records, first_seq=first_seq)]


def _armed(conn: FakeConnection | None = None, **kwargs: Any) -> rw.RecordWriter:
    """A writer armed with a fixed DSN whose driver hook yields `conn`."""
    target = conn if conn is not None else FakeConnection()
    return rw.RecordWriter(dsn="postgresql://record/db",
                           connect=lambda _dsn: target, **kwargs)


