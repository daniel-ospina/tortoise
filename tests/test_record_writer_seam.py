# 6. ARMED-BUT-UNREACHABLE FAILS — it never reads as unarmed
# ════════════════════════════════════════════════════════════════════════════


def test_an_unreachable_record_fails_the_write_instead_of_reading_as_unarmed() -> None:
    """`degraded` (configured, down) must never collapse into `unconfigured`.

    Truth-first (§3/§17.1): a capture that reports success while the record is
    unreachable claims a durability that did not happen. The failure is loud,
    it is the seam's one catchable class, and the cause is preserved unchanged.
    """
    def refuse(_dsn: str) -> Any:
        raise OSError("connection refused")

    writer = rw.RecordWriter(dsn="postgresql://record/db", connect=refuse)

    with pytest.raises(rw.RecordWriteError) as excinfo:
        writer.write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert isinstance(excinfo.value.__cause__, OSError)
    # And the condition is the recorded OUTAGE term, not the set-up gap.
    assert status_vocabulary.classify(configured=True, reached=False) == (
        status_vocabulary.STATUS_DEGRADED)


def test_an_execution_failure_propagates_wrapped_with_the_cause_intact() -> None:
    """A Postgres error mid-plan is a failed write, not a partial success."""
    class Exploding(FakeConnection):
        def cursor(self) -> FakeCursor:
            raise RuntimeError("server closed the connection unexpectedly")

    with pytest.raises(rw.RecordWriteError) as excinfo:
        _armed(Exploding()).write(RECORDS, org_id=ORG, graph_id=GRAPH)
    assert isinstance(excinfo.value.__cause__, RuntimeError)


def test_a_failed_write_disposes_of_the_connection_the_seam_opened() -> None:
    """The seam closed what it opened and could not use — the caller has no handle.

    On failure the caller receives an exception, never `RecordWrite.connection`,
    so it can neither roll back nor close the connection the seam opened for
    itself. Leaving it open orphans a live connection, its aborted server-side
    transaction and its backend slot for as long as the exception is held (which
    is exactly what `exc_info` logging, telemetry and retry wrappers do) — and
    on a degraded record this repeats per capture. Closing aborts the
    transaction, the only outcome left once nobody can see it.
    """
    class Exploding(FakeConnection):
        def cursor(self) -> FakeCursor:
            raise RuntimeError("server closed the connection unexpectedly")

    conn = Exploding()
    with pytest.raises(rw.RecordWriteError):
        _armed(conn).write(RECORDS, org_id=ORG, graph_id=GRAPH)

    assert conn.closed == 1
    assert (conn.commits, conn.rollbacks) == (0, 0)   # disposal is a close only


def test_a_failed_write_never_closes_the_callers_injected_connection() -> None:
    """An injected connection outlives the failure: the caller still owns it.

    The counterpart pin. Closing a handle the caller is mid-transaction on would
    abort work the seam knows nothing about — and would silently discard the
    journal append that shares that transaction.
    """
    class Exploding(FakeConnection):
        def cursor(self) -> FakeCursor:
            raise RuntimeError("deadlock detected")

    injected = Exploding()
    with pytest.raises(rw.RecordWriteError):
        _armed().write(RECORDS, org_id=ORG, graph_id=GRAPH, conn=injected)

    assert injected.closed == 0
    assert (injected.commits, injected.rollbacks) == (0, 0)


def test_a_refused_batch_also_disposes_of_the_opened_connection() -> None:
    """Totality refuses BEFORE any statement — the connection is still the seam's.

    A refusal is the common armed-path failure on a bad record type, and it must
    not leak the connection either.
    """
    conn = FakeConnection()
    batch = [*RECORDS[:2], {"type": "SomethingNobodyDeclared", "ts": "T",
                            "id": "x"}]

    with pytest.raises(rw.RecordWriteError) as excinfo:
        _armed(conn).write(batch, org_id=ORG, graph_id=GRAPH)

    assert isinstance(excinfo.value.__cause__, rp.RecordProjectionError)
    assert conn.statements() == []
    assert conn.closed == 1


