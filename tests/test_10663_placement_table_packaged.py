"""#10663 — the placement table must be IN THE PACKAGE, not in `docs/`.

WHAT THIS PINS. `tortoise/cache_projection.py` reads the record's property
namespace from the field-level placement table, whose one declaration is prose:
``docs/epics/2026-10-10-7879-postgres-record/02-identity-and-placement.md``.
The DEPLOYED IMAGE ships no ``docs/`` tree, so ``record-reconcile`` and
``record-restore`` could not run in production at all. Measured in the shipped
image (``ghcr.io/daniel-ospina/tortoise-selfhost:latest``, same COPY set as
``Dockerfile.hosted``, on a real Postgres record + real FalkorDB)::

    $ tortoise record-reconcile --db … --record-dsn … --org … --graph …
    Record↔cache reconciliation UNAVAILABLE: record is unreadable
      (CacheProjectionError) — divergence is UNKNOWN, not zero
    EXIT=2

    # …and the cause, which the CLI could not show:
    CacheProjectionError: the placement table is not on disk at
    /app/docs/epics/2026-10-10-7879-postgres-record/02-identity-and-placement.md

The carrier (``tortoise/_placement_table.json``, generated by
``tools/gen_placement_table.py``) is therefore shipped as package data, and the
tests below pin the three properties that make that a FIX rather than a copy:

* the carrier MATCHES the doc — one declaration, two carriers, no drift;
* the RUNTIME never needs ``docs/`` — proved by pointing ``PLACEMENT_DOC`` at a
  path that does not exist, which is the deployed shape simulated without a
  container;
* the WHEEL/SDIST carries it — the ``package-data`` pattern is evaluated against
  the tree (the ``test_capture_install`` precedent: a lost entry there is
  silent for every source checkout and fatal for every installed user).

Plus the message half (#10663's option (c)): with neither carrier present the
refusal is a NAMED packaging fault, and the CLI says so instead of pointing an
operator at Postgres credentials.
"""

from __future__ import annotations

import fnmatch
import json
import sys
import tomllib
from pathlib import Path

import pytest
import yaml

from tortoise import __main__ as cli
from tortoise import cache_projection as cp

REPO_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = REPO_ROOT / "pyproject.toml"


@pytest.fixture(autouse=True)
def _clear_placement_caches():
    """Every accessor below is memoized; a monkeypatched path must not hide.

    Without this, the first test to populate `placement_columns()` decides what
    every later test sees — the classic memoized-pin false green.
    """
    for fn in (cp.placement_spellings, cp.placement_columns,
               cp.projected_columns):
        fn.cache_clear()
    yield
    for fn in (cp.placement_spellings, cp.placement_columns,
               cp.projected_columns):
        fn.cache_clear()


# ── 1. The carrier and the doc cannot drift ────────────────────────────────


def test_the_carrier_ships_inside_the_package():
    """Not beside it, not above it: inside `tortoise/`, which every image COPYs."""
    assert cp.PACKAGED_PLACEMENT_TABLE.exists(), (
        f"the packaged placement table is missing at "
        f"{cp.PACKAGED_PLACEMENT_TABLE} — regenerate it with "
        f"`uv run python tools/gen_placement_table.py`")
    assert cp.PACKAGED_PLACEMENT_TABLE.parent == Path(cp.__file__).parent


def test_the_carrier_declares_exactly_what_the_doc_declares():
    """THE DRIFT PIN — both directions, in order, without the schema extras.

    `_read_placement_rows(doc=…)` parses the doc and appends
    `ADDITIONAL_PRIMARY_COLUMNS`; the carrier holds only the doc's rows. So the
    comparison is carrier-vs-parsed-doc, and the extras are proved present in
    the RUNTIME answer by the next test.
    """
    from_carrier = cp._read_packaged_placement_rows()
    from_doc = cp.parse_placement_rows(
        cp.PLACEMENT_DOC.read_text(encoding="utf-8"))
    assert from_carrier is not None, "the carrier is missing"
    assert from_carrier == from_doc, (
        "tortoise/_placement_table.json does not match the placement table doc "
        "— the doc is the ONE declaration, so the carrier is regenerated, never "
        "hand-edited: `uv run python tools/gen_placement_table.py`")


def test_the_generator_reproduces_the_committed_carrier_byte_for_byte():
    """`--check` in test form: the generator, not a re-parse, is authoritative."""
    sys.path.insert(0, str(REPO_ROOT / "tools"))
    try:
        import gen_placement_table
    finally:
        sys.path.pop(0)
    assert gen_placement_table.build() == cp.PACKAGED_PLACEMENT_TABLE.read_text(
        encoding="utf-8"), (
        "the committed carrier is stale against its own generator — run "
        "`uv run python tools/gen_placement_table.py`")


def test_the_runtime_answer_carries_the_schema_spelled_extras():
    """The extras are appended by `cache_projection`, never invented by the carrier."""
    rows = cp._read_placement_rows()
    for table, extra in cp.ADDITIONAL_PRIMARY_COLUMNS.items():
        for prop in extra.values():
            assert (table, prop) in rows


# ── 2. The deployed shape: no `docs/` on disk ──────────────────────────────


def test_the_runtime_read_never_needs_the_docs_tree(tmp_path, monkeypatch):
    """THE #10663 PICTURE, container-less: `docs/` absent, the verb still reads.

    `PLACEMENT_DOC` is pointed at a path that does not exist — exactly the
    deployed image, where `/app/docs` is not COPY'd — and every runtime accessor
    must still answer from the package. This is the assertion the shipped image
    was missing: without it, CI reads a checkout (which HAS `docs/`) and reports
    a verb green that cannot start in production.
    """
    gone = tmp_path / "no-such-docs-tree" / "02-identity-and-placement.md"
    monkeypatch.setattr(cp, "PLACEMENT_DOC", gone)

    rows = cp._read_placement_rows()
    assert rows, "no placement rows resolved without the docs tree"

    columns = cp.placement_columns()
    # Two independent probes: a schema-spelled extra and a doc-spelled camelCase
    # property that the projection's MERGE actually writes.
    assert columns["point"]["point_kind"] == "pointKind"
    assert columns["event"]["event_id"] == "eventId"
    assert "point_kind" in cp.projected_columns("point")
    assert cp.canonical_property("point", "point_kind") == "pointKind"


def test_a_missing_carrier_falls_back_to_the_doc_in_a_checkout(tmp_path,
                                                             monkeypatch):
    """THE FALLBACK BRANCH (#10663 review, P2 — it had no test at all).

    A checkout whose carrier was dropped (a stale clone, a wiped working tree)
    still has the doc, and `_read_placement_rows()` must read it rather than
    refuse. The two carrier-removal tests around this one patch BOTH carriers
    absent and so exercise only the "raise" path; without this one, deleting
    the fallback — or turning a missing carrier into a raise instead of `None`
    — merged green, and every record verb in such a checkout would refuse with
    no signal.
    """
    monkeypatch.setattr(cp, "PACKAGED_PLACEMENT_TABLE", tmp_path / "absent.json")
    assert cp.PLACEMENT_DOC.exists(), "the fixture presumes a source checkout"

    from_doc = cp._placed_rows_with_extras(
        cp.parse_placement_rows(cp.PLACEMENT_DOC.read_text(encoding="utf-8")))
    assert cp._read_placement_rows() == from_doc
    assert cp.placement_columns()["point"]["point_kind"] == "pointKind"


def test_both_carriers_missing_is_a_named_packaging_fault(tmp_path, monkeypatch):
    """Option (c): name BOTH locations, and say it is the INSTALL, not the record."""
    monkeypatch.setattr(cp, "PACKAGED_PLACEMENT_TABLE", tmp_path / "absent.json")
    monkeypatch.setattr(cp, "PLACEMENT_DOC", tmp_path / "absent.md")

    with pytest.raises(cp.PlacementTableUnavailable) as excinfo:
        cp._read_placement_rows()

    message = str(excinfo.value)
    assert "PACKAGING fault" in message
    assert str(tmp_path / "absent.json") in message
    assert str(tmp_path / "absent.md") in message
    assert "gen_placement_table.py" in message
    # Still a CacheProjectionError, so every existing handler keeps its shape.
    assert isinstance(excinfo.value, cp.CacheProjectionError)


def test_a_corrupt_carrier_is_reported_not_silently_fallen_back(tmp_path,
                                                               monkeypatch):
    """A malformed carrier must not be papered over by the doc."""
    corrupt = tmp_path / "_placement_table.json"
    corrupt.write_text("{not json", encoding="utf-8")
    monkeypatch.setattr(cp, "PACKAGED_PLACEMENT_TABLE", corrupt)

    with pytest.raises(cp.PlacementTableUnavailable) as excinfo:
        cp._read_placement_rows()
    assert "is unreadable" in str(excinfo.value)
    assert "INSTALL" in str(excinfo.value)


def test_an_empty_carrier_is_refused_not_read_as_no_rows(tmp_path, monkeypatch):
    """A carrier that parses to ZERO rows is a packaging fault, not a namespace.

    THE SILENT-EMPTY CLASS, one artefact over (#10663 review, P2). `{"rows": []}`
    parses cleanly and yields an empty namespace, so every record property would
    project as **unmapped**, in production, with no error — measured before the
    guard: `_read_placement_rows()` returned the 4 `ADDITIONAL_PRIMARY_COLUMNS`
    extras alone and `placement_columns()` lost `point_kind`.

    Every pin in section 1 is RELATIVE — the carrier is compared to the same
    parser over the doc, and the generator to the committed bytes — so a
    generator that emitted nothing agrees with itself and keeps all of them, and
    `--check`, green. Nothing else in the tree reads the SHIPPED artefact.
    """
    empty = tmp_path / "_placement_table.json"
    empty.write_text(json.dumps({"rows": [], "_source_sha256": "0" * 64}),
                     encoding="utf-8")
    monkeypatch.setattr(cp, "PACKAGED_PLACEMENT_TABLE", empty)
    assert cp.PLACEMENT_DOC.exists(), "the fixture presumes a source checkout"

    with pytest.raises(cp.PlacementTableUnavailable) as excinfo:
        cp._read_placement_rows()

    message = str(excinfo.value)
    assert "EMPTY" in message, message
    assert str(empty) in message
    assert "gen_placement_table.py" in message
    # Still a CacheProjectionError, so every existing handler keeps its shape.
    assert isinstance(excinfo.value, cp.CacheProjectionError)

    # …and the SAME refusal reaches `placement_columns()`, which is the call the
    # projection actually makes — an empty namespace must never be usable.
    with pytest.raises(cp.PlacementTableUnavailable):
        cp.placement_columns()


# ── 3. The carrier reaches an installed user ───────────────────────────────


def test_the_carrier_is_declared_as_package_data():
    """The `test_capture_install` precedent: evaluate the pattern against the tree.

    A missing `package-data` entry is invisible in every source checkout and
    fatal in every image and wheel — the same silent-empty class #1929/#9231
    each closed for a different artefact.
    """
    config = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    patterns = config["tool"]["setuptools"]["package-data"]["tortoise"]
    name = cp.PACKAGED_PLACEMENT_TABLE.name
    assert any(fnmatch.fnmatch(name, pattern) for pattern in patterns), (
        f"{name} matches none of pyproject's `tool.setuptools.package-data."
        f"tortoise` patterns {patterns} — an installed `tortoise` would ship no "
        f"placement table and every record verb would refuse (the #10663 "
        f"defect, on the wheel path)")


