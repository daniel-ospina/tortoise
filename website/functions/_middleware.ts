// Host-based routing for premiselabs.co Pages project.
//
// Topology (ONE marketing host — epic #11762, owner decision 2026-11-10):
//   premiselabs.co/           → company page     (index.html)
//   premiselabs.co/tortoise/… → product surface  (product.html + docs/faq/…)
//   premiselabs.co/blog       → blog             (the blog Functions)
//   premiselabs.co/{privacy,tos,dpa} → legal, at the ROOT (they govern the
//                               business, not the product)
//   tortoise.premiselabs.co   → PERMANENT 301 onto the paths above. The host is
//                               kept alive forever; its DNS and Pages binding
//                               are a fixture, never a leftover.
//   app.premiselabs.co        → dashboard (separate tortoise-dashboard project)
//
// Cloudflare Pages serves one project per custom domain, so we route by Host
// header in a middleware. Every static asset is served on BOTH marketing hosts,
// so the product surface used to be reachable on premiselabs.co at a second set
// of URLs; the 2026-08-17 pass consolidated THAT direction (company → tortoise).
// This file now inverts it: the company host is the ONE marketing host and the
// product host 301s onto it (see the two blocks below).
//
// ⛔ ORDER MATTERS, and the AUTH split is why. The AUTH surface (auth, signup,
// welcome, invite-accept) lives on the app origin — issue #4054 — and its
// branches are HOST-INDEPENDENT: the bare `/auth` with the grandfathered 301,
// the `/auth/*` subtree with a 302 (#4346 — a NEW branch is 302 per
// `SCOPE.md` §12/F12). The blog admin console moved there too — issue #4171 —
// because its session (`__Host-session`) is host-only on app.premiselabs.co; a
// single unconditional /admin 302 lives below (#4409 resolved it from 301).
// Both run BEFORE the product-host block, so a 301-off-the-product-host never
// pre-empts a pinned app-origin decision.
//
// The product page has ONE canonical URL now, `premiselabs.co/tortoise`, served
// by the rewrite at the bottom. The raw /product, /product.html and /index.html
// assets are duplicates of it and consolidate onto it.
//
// HSTS (#1003 §1): Cloudflare does NOT apply _headers rules to responses
// generated by Pages Functions, so the header must be stamped here on every
// response this middleware constructs (the static-asset fallthroughs via
// context.next() are covered by website/_headers). Value matches the API
// (tortoise/hosted_api.py): max-age=31536000; includeSubDomains — no
// `preload` yet, soak first per #1003 §1.
import { RELAXED_CSP } from "./_shared/security-headers.ts";

const HSTS = { "Strict-Transport-Security": "max-age=31536000; includeSubDomains" };

// ── A stray OAuth authorization response must be REFUSED, not rendered (#10088 ask 3) ──
//
// The measured failure (issue #10088, D2): GoTrue did not honour `redirect_to`,
// substituted the project **Site URL**, and delivered a LIVE authorization code
// to a marketing page —
//
//     https://tortoise.premiselabs.co/?code=50605f24-15a1-40f0-8e86-f3722cccce13#
//
// — which rendered normally, ignored the parameter and silently discarded the
// code. The user saw a product page and the connector was never connected; the
// code was burned, so their natural "try again" cost a fresh authorize request
// and looked like a flaky connector. Supabase documents HALF the mechanism —
// "The Site URL in URL Configuration defines the default redirect URL when no
// `redirectTo` is specified in the code" (docs/guides/auth/redirect-urls) — and
// the other half ("or `redirectTo` was not accepted") is not in that page: it is
// THIS project's own measurement, that a VALID code arriving on the Site URL is
// GoTrue's allow-list-rejection signature (issue #10088, 2026-10-26
// re-measurement). RFC 9700 puts the obligation on the receiving side: verify
// the response arrived at the EXPECTED redirect URI and ABORT the flow on a
// mismatch.
//
// This project serves no OAuth callback on ANY path — the callback moved to the
// app origin (#4054), which is exactly why the `/auth/*` surface 302s there —
// so a `code` arriving here is always misdirected. The refusal is therefore keyed
// to the PARAMETER, not to a path, and it fires before any asset is fetched: a
// page that renders and discards the credential is the defect, and a page that
// renders AROUND the refusal is the same defect with nicer words.
//
// What the refusal deliberately does NOT do:
//   * no Location — forwarding a code the AS never issued for that origin only
//     moves the misdirection (and the wrong-origin `/auth/callback` case is a
//     recorded, pinned 302 whose cleanup is the OPEN audit #8680, not this lane);
//   * no echo of `code`/`error_description` — a credential in a URL leaks via
//     browser history, `Referer`, CDN logs and analytics, and OAuth error text
//     is attacker-influenced; hence `Referrer-Policy: no-referrer` and a CSP
//     that permits no third-party resource at all;
//   * no cacheability — `no-store`, or a cached refusal would be served to the
//     next ordinary visitor of the page it refuses.
//
// `code_challenge` (a PKCE verifier HASH, present on ordinary authorize links)
// and a bare `error` (which a marketing link may legitimately carry) are NOT the
// authorization-response shape and deliberately fall through — an over-block
// here would fail closed on a real visitor.
//
// ⛔ `code` ONLY — GoTrue's ERROR shape (`error` + `error_description` /
// `error_code`) is deliberately NOT refused, and that is a recorded behaviour,
// not an oversight. `website/product.html:349-355` documents it and its handler
// at `:510-535` renders the #1224 banner on exactly this URL:
//
//     <!-- OAuth error banner (#1224): Supabase redirects here with
//          ?error=...&error_code=bad_oauth_state when the OAuth state TTL
//          expired mid-login — surface it instead of failing silently. -->
//
// That shape carries NO credential, so refusing it protects nothing, and it
// would retire the banner: an expired dashboard-login state would be answered
// with this page's connector instructions ("start again from your MCP client …
// ChatGPT: Settings → Connectors"), which are wrong for a plain login and whose
// retry path leads to the connector, not back to the sign-in. Ask 3 is about a
// stray `code`; the error shape already did what the ask wants ("surface it
// instead of failing silently"), so it keeps doing it.
const STRAY_RETURN_CSP =
  "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; " +
  "form-action 'none'; frame-ancestors 'none'";

// `code` ONLY — see the header block above for why GoTrue's `error` shape is
// left to `website/product.html`'s #1224 banner. `has()` is an exact-key match,
// so `code_challenge` cannot be mistaken for `code`.
function isStrayAuthorizationCode(url: URL): boolean {
  return url.searchParams.has("code");
}

function strayReturnRefusal(): Response {
  // Self-contained: no external stylesheet, no font, no script. The page must
  // not make a single outbound request while a credential is in its URL.
  const body = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex">
<title>This sign-in did not return to the connector</title>
<style>
body{margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;
background:#0b0b0d;color:#f2f2f4;font:16px/1.55 system-ui,-apple-system,Segoe UI,Roboto,sans-serif}
main{max-width:34rem;padding:2.5rem 1.5rem}
h1{font-size:1.35rem;line-height:1.3;margin:0 0 1rem}
p{margin:0 0 1rem;color:#c9c9d1}
a{color:#8ab4ff}
</style></head><body><main>
<h1>This sign-in did not return to the connector</h1>
<p>Your browser arrived here with a one-time sign-in code, but this page is not
the one that code belongs to, so it cannot be completed here. Nothing was
connected, and the code has now expired.</p>
<p><strong>To finish connecting, start again from your MCP client</strong> (for example
ChatGPT: <em>Settings &rarr; Connectors &rarr; Connect another account</em>) and complete the
sign-in in the window it opens.</p>
<p>If it keeps happening, please <a href="/contact">tell us</a> — quote the time you
tried, not the code.</p>
<p><a href="/">Continue to the site</a></p>
</main></body></html>`;
  return new Response(body, {
    status: 400,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Cache-Control": "no-store",
      "Referrer-Policy": "no-referrer",
      "Content-Security-Policy": STRAY_RETURN_CSP,
      ...HSTS,
    },
  });
}

export const onRequest: PagesFunction = async (context) => {
  const url = new URL(context.request.url);
  const host = context.request.headers.get("host") || "";

  // ── ONE marketing host (epic #11762) ──────────────────────────────────
  // The shared Pages project serves every static asset on BOTH hosts, so the
  // product surface was reachable on premiselabs.co at a second set of URLs —
  // Google crawled both copies ("Alternate page with proper canonical tag"
  // ×5). The 2026-08-17 pass consolidated company → tortoise. This block
  // inverts it, on the owner decision of 2026-11-10: company at the ROOT,
  // product under /tortoise, blog at /blog, and the product host 301s onto
  // them FOREVER.
  //
  // ⛔ A 301 is browser-PERSISTENT and cannot be reclaimed by a later deploy,
  // so a redirect branch may only ship when its target resolves to a 200 in
  // the SAME deploy. That is why the product page and the product set are
  // SERVED under the prefix by the rewrite at the bottom of this file rather
  // than left for the file move: a 301 onto a 404 is an outage, not a
  // migration.
  //
  // Scoped to the EXACT company hostname: local dev (wrangler pages dev,
  // host=127.0.0.1) and *.pages.dev previews keep the pass-through so the
  // legal E2E suite can run against a dev server and previews stay
  // navigable (neither is indexed; no SEO impact). Runtime fetches (the
  // tortoise-onboarding instructions at app.premiselabs.co/skills/...) are not in the
  // set. The auth surface has its own origin split — see APP_ONLY below.
  const APP_ORIGIN = "https://app.premiselabs.co";
  const COMPANY_ORIGIN = "https://premiselabs.co";
  const PRODUCT_ORIGIN = "https://tortoise.premiselabs.co";
  // The product's canonical home on the ONE marketing host.
  const PRODUCT_PREFIX = "/tortoise";

  const APP_ONLY = new Set([
    "/signup", "/signup.html",
    "/auth", "/auth.html",
    "/welcome", "/welcome.html",
    "/invite-accept", "/invite-accept.html",
  ]);

  // The PRODUCT surface: the pages that render product content. They move
  // WITH the product page, under PRODUCT_PREFIX.
  const PRODUCT_PAGES = new Set([
    "/docs", "/docs.html",
    "/faq", "/faq.html",
    "/security", "/security.html",
    "/self-hosted", "/self-hosted.html",
    "/license", "/license.html",
    // The design-partner one-pager. A prospect-facing document linked from
    // outreach, not from the site nav — but it is a real page on the shared
    // Pages project, so without this entry premiselabs.co serves its own copy
    // at a second host. It is noindex, so this is not about an indexed
    // duplicate: it is that the document has ONE canonical address, and an
    // outreach link must not land a prospect on a host that serves the same
    // page under a different URL (the consolidation this block exists for).
    "/design-partners-intro", "/design-partners-intro.html",
    // The investor one-pager (#8568). It is a real page on the shared Pages
    // project like its design-partner sibling above, so without this entry the
    // company host serves its own copy at a second URL. Its canonical address
    // is the tortoise host — the document has ONE address.
    "/investors", "/investors.html",
  ]);

  // The legal pages that govern the BUSINESS, not the product. Epic #11762
  // settled that fork explicitly: these stay at the company ROOT, so they are
  // NOT under PRODUCT_PREFIX and the company host must NOT redirect them (it
  // did, when the product host owned them).
  const LEGAL_AT_ROOT = new Set([
    "/privacy", "/privacy.html",
    "/tos", "/tos.html",
    "/dpa", "/dpa.html",
  ]);

  // `/signin` is a legacy ALIAS, not a page: `_redirects` maps it to `/auth`,
  // which lives on the APP origin (#4054). It is resolved to the app origin in
  // ONE hop on whichever host is asked — and it is deliberately NOT a member of
  // PRODUCT_PAGES, because moving it under the prefix would give it a second,
  // wrong canonical (the app origin has no `/signin` route).
  const SIGNIN_ALIAS = new Set(["/signin", "/signin.html"]);

  // RETIRED page (#9486): the Spanish LFPDPPP notice is gone (the controller
  // is UK-resident). Kept DELIBERATELY so the retired route consolidates onto
  // the canonical host in the FIRST Location instead of becoming host- or
  // host+hop-dependent. Its terminal target is `/privacy`, which is a 200 on
  // the company host.
  const RETIRED_PRIVACY_ALIAS = new Set(["/aviso-privacidad", "/aviso-privacidad.html"]);

  // The raw product-page assets. The product page is SERVED at PRODUCT_PREFIX
  // by the rewrite at the bottom, so these are duplicates of it and consolidate
  // onto that one URL (SEO: "Duplicate without user-selected canonical").
  // ⛔ `/index.html` is NOT here: on the product host it is a duplicate of the
  // product root, but on the COMPANY host it is a duplicate of the COMPANY page
  // and belongs to `_redirects` — the product host's block adds it explicitly.
  const PRODUCT_ROOT = new Set(["/product", "/product.html"]);

  // ── ONE definition of a product URL's canonical form ──────────────────
  // No leading/trailing slashes, no `.html`. Both hosts derive from THIS, because
  // the product host hands the request to the company host while the company host
  // serves it: if the two normalised differently, one of them would become a
  // second hop — and a hop chain is how a migration loses equity silently. A
  // non-canonical `/tortoise` spelling therefore costs exactly one redirect, and
  // an unknown one is a 404 rather than a 301 onto a 404.
  const productRest = (pathname: string) =>
    pathname
      .slice(PRODUCT_PREFIX.length)
      .replace(/^\/+/, "")
      .replace(/\/+$/, "")
      .replace(/\.html$/, "");
  const productCanonical = (rest: string) =>
    rest === "" ? PRODUCT_PREFIX : `${PRODUCT_PREFIX}/${rest}`;

  const COMPANY_HOSTS = new Set(["premiselabs.co"]);
  // Trailing-slash-stripped pathname, the form every path set below is keyed on.
  const path = url.pathname.replace(/\/+$/, "") || "/";

  // ── A stray OAuth authorization response is REFUSED before ANY branch runs ──
  // It sits ABOVE the host-consolidation block because THAT block is a
  // forwarding branch: it returns 301s that PRESERVE the query string
  // (`+ url.search`), so a code on `premiselabs.co/docs`, `/faq`, `/signin` or
  // `/blog/*` was carried in a `Location` to the tortoise host and only refused
  // after that extra hop — one more URL, one more CDN log line, one more browser
  // history entry containing the credential, for no gain. The refusal is keyed
  // to the PARAMETER, so it belongs ahead of every branch that can put the code
  // in a `Location`, not merely ahead of the branches that render.
  //
  // EXEMPT — the surfaces where a `code` is forwarded rather than refused. The
  // reason is NOT "the origin can redeem it" (PR #10514 review, finding 2: that
  // premise is false for five of the six shapes, and the backstop's own comment
  // down this file says so — the app's `signup.html` reads `next`/`mode`/
  // `error`, `invite-accept.html` reads `token`, `welcome.html` and `/admin`
  // read nothing, and `/auth` hands off to an app page that redeems nothing
  // either). The reason is that these redirects are PINNED DECISIONS, and
  // refusing a code on one of them would replace a decided redirect with a 400:
  //   * the auth surface — `/auth` (+`.html`) and the `/auth/*` BFF subtree
  //     (#4054/#4346). This is the ONE shape that redeems a code today:
  //     `/auth/callback` really does exchange it (its wrong-origin allow-list
  //     entry is the OPEN audit #8680, not this lane's);
  //   * `/admin`, the operator console on the session origin (#4171/#4409);
  //   * the APP_ONLY pages, which the company-host block 301s to that same app
  //     origin (`/signup`, `/welcome`, `/invite-accept`, #4054). A refusal here
  //     would break the signup funnel, the operator console, or turn a stale
  //     bookmark / pre-cutover email link into the dead end #4328 rejects.
  // Everything else in this project can only RENDER a page, so a code on it is
  // un-redeemable and is refused here. The guard below (after the 30x branches)
  // stays as the backstop for anything exempt-shape that still reaches it.
  //
  // ⚠ Because this exemption sits IN FRONT of the primary guard, these shapes
  // still construct a `Location` that carries the code. That is the one exception
  // to the "no `Location`" framing in the header above, it is deliberate (the
  // pinned redirect wins), and the PR's Residual list records it — split in TWO,
  // because the two classes are NOT the same shape and the earlier one-line
  // version of this note under-reported the second (PR #10514 review, finding 4):
  //   * `APP_ONLY` (`/signup`, `/welcome`, `/invite-accept`) — HOST-SPLIT: the
  //     company host 301s to the app origin carrying the code
  //     (`premiselabs.co/signup?code=…` → `app.premiselabs.co/signup?code=…`); on
  //     `tortoise.*`/previews there is no middleware branch, so the request falls
  //     to the BACKSTOP below and is refused 400;
  //   * `/auth`, `/auth.html` (301), `/auth/*` (302) and `/admin`, `/admin/*`
  //     (302) — HOST-INDEPENDENT: those branches run on every host, so their
  //     `Location` carries the code on `premiselabs.co`, on `tortoise.*` and on a
  //     `*.pages.dev` preview alike. Measured on all three hosts.
  // Do NOT "complete" the guard by refusing these — that reverses #4054/#4171/
  // #4409 with nothing in the change saying so.
  const forwardsCredential =
    APP_ONLY.has(path) ||
    url.pathname.startsWith("/auth/") ||
    url.pathname === "/admin" ||
    url.pathname === "/admin/" ||
    url.pathname.startsWith("/admin/");
  if (!forwardsCredential && isStrayAuthorizationCode(url)) {
    return strayReturnRefusal();
  }

  // Blog prefix rule (#1796): /blog and /blog/<anything> (incl. trailing
  // slash) are ONE page with ONE canonical host — which is the COMPANY host
  // since #11762 (it was the product host when #1796 landed). Exact prefix
  // only: /blogpost and /blog-extra must NOT match (E2E-7). The agent API
  // (/blog/api/*) is EXCLUDED — it must not be 301'd (a redirect would turn
  // POST into GET and drop the body), so it keeps passing through on BOTH
  // hosts.
  const isBlogPath =
    !url.pathname.startsWith("/blog/api/") &&
    (url.pathname === "/blog" ||
      url.pathname === "/blog/" ||
      url.pathname.startsWith("/blog/"));

  // Host-header hygiene: strip port + trailing dot before matching.
  const hostKey = host.replace(/:\d+$/, "").replace(/\.$/, "");
  if (COMPANY_HOSTS.has(hostKey)) {
    // ⛔ The blog is SERVED here now (#11762): this block used to 301 /blog* to
    // the product host. It passes through instead, so the blog Functions serve
    // it and its canonicals can follow on the same host (#11765/#11976).
    //
    // Auth moved to the APP origin (#4054) — the company-host copies 301
    // there. Same normalization and query-string preservation as below:
    // invite ?token=…, recovery ?type=recovery and OAuth ?error=… must survive.
    if (path !== "/" && APP_ONLY.has(path)) {
      const target = APP_ORIGIN + path.replace(/\.html$/, "") + url.search;
      return new Response(null, {
        status: 301,
        headers: { Location: target, ...HSTS },
      });
    }
    // `/signin` is an alias for an app-origin page, so it resolves there in one
    // hop rather than becoming a same-host page under PRODUCT_PREFIX.
    if (SIGNIN_ALIAS.has(path)) {
      return new Response(null, {
        status: 301,
        headers: { Location: APP_ORIGIN + "/auth" + url.search, ...HSTS },
      });
    }
    // The product set moves UNDER the prefix — still a 301 (the redirect these
    // pages already had), only the TARGET changes: same host, product path.
    // Normalize to the extensionless canonical so the raw .html form costs one
    // hop, and PRESERVE the query string.
    if (PRODUCT_PAGES.has(path)) {
      const target = COMPANY_ORIGIN + PRODUCT_PREFIX + path.replace(/\.html$/, "") + url.search;
      // Build the 301 manually — Response.redirect() returns a response with
      // IMMUTABLE headers, so stamping HSTS on it throws (Cloudflare 1101 /
      // 500 on every consolidated URL). Headers passed in the constructor
      // are the response's own and mutable.
      return new Response(null, {
        status: 301,
        headers: { Location: target, ...HSTS },
      });
    }
    // The raw product assets are duplicates of what PRODUCT_PREFIX serves.
    if (PRODUCT_ROOT.has(path)) {
      return new Response(null, {
        status: 301,
        headers: { Location: COMPANY_ORIGIN + PRODUCT_PREFIX + url.search, ...HSTS },
      });
    }
    // ⛔ LEGAL_AT_ROOT is deliberately ABSENT: these pages live at this very
    // host's root now, so they must pass through to their own assets. And the
    // RETIRED_PRIVACY_ALIAS is absent too — passing through lets the committed
    // `_redirects` rule take it to `/privacy` in one hop, exactly as it does
    // today (the middleware used to pre-empt that with a cross-host hop).
  }

  // ── Auth lives on the APP origin (#4054) ──────────────────────────────
  // This project used to serve the one auth screen at /auth from the
  // signup.html asset. The BFF and the three pages it serves moved to the
  // `tortoise-dashboard` project (app.premiselabs.co), so this project can no
  // longer render them. The company-host block above already 301'd the auth
  // paths to the app origin; this covers the tortoise host (and previews/dev)
  // so a request for /auth does not fall through to a DELETED asset. PRESERVE
  // the query string — the #1224 OAuth state-expiry banner reads ?error=…
  // here, and invite / recovery links carry ?token=… / ?type=recovery.
  if (url.pathname === "/auth" || url.pathname === "/auth.html") {
    return new Response(null, {
      status: 301,
      headers: { Location: APP_ORIGIN + "/auth" + url.search, ...HSTS },
    });
  }

  // ── The BFF's OWN endpoints, same move (#4054) ────────────────────────
  // `/auth/start`, `/auth/callback`, `/auth/confirm`, `/auth/update-password`,
  // `/auth/reset`, `/auth/resend`, `/auth/link`, `/auth/api-key` and
  // `/auth/set-email` moved to the app origin with the BFF. The exact-path rule
  // above does NOT cover them, so without this branch they fall through to a
  // DELETED asset and answer 404 — which is what a stale bookmark, a
  // pre-cutover email link, or a relative link resolved against the marketing
  // host used to hit.
  //
  // NOT a 404, deliberately (#4328). Removing a dormant OAuth endpoint is the
  // OAuth-BCP default, and it is the wrong control here: the endpoint is dormant
  // on THIS origin while the links that reach it are not, so a 404 only turns a
  // stale bookmark or a pre-cutover email link into a dead end. The inbound
  // query reaches this worker's logs either way, so the status code buys no
  // security.
  //
  // What keeps the redirect safe is upstream of it: GoTrue refuses a
  // `redirect_to` it does not recognise, so the guard is the identity provider's
  // redirect allow-list. The property that MUST hold is that no allow-list entry
  // authorises a code for THIS origin's `/auth/callback`. The entries required
  // today are recorded in `docs/ops/auth-email-flows.md` §3 — which still lists
  // `https://tortoise.premiselabs.co` for legacy links, so the list is wider than
  // the app origin — and #8680 is the OPEN audit that confirms the legacy
  // `/auth/callback` entry can be removed. That audit is not closed.
  //
  // 302, NOT 301 — a deliberate departure from the ordinary "moved ⇒ 301"
  // practice, which is why the OVERRIDES marker for it lives on #3501 / #3521 /
  // #4409 and in `SCOPE.md` §12: a 301 is browser-persistent and CANNOT be
  // reclaimed by a later deploy, so every NEW branch for the moved surface is 302
  // (`SCOPE.md` §12 “302, never a new 301”). The `/auth` 301 directly above is
  // the one #4054 shipped and is deliberately left alone — it is already in
  // browsers' caches, so changing it is its own decision.
  //
  // Query-preserving and single-hop, both per W2. The bare `/auth/` collapses
  // onto `/auth` here rather than bouncing through `_redirects` first, which
  // also removes the old two-hop chain (`/auth/` → `/auth` → app).
  if (url.pathname.startsWith("/auth/")) {
    const path = url.pathname === "/auth/" ? "/auth" : url.pathname;
    return new Response(null, {
      status: 302,
      headers: { Location: APP_ORIGIN + path + url.search, ...HSTS },
    });
  }

  // ── The blog admin console lives on the APP origin (#4171) ────────────
  // #4054 moved the BFF (and the `__Host-session` cookie) to
  // app.premiselabs.co, but the console stayed on this project — so its
  // relative `/api/session` check fell through to the SPA shell (a 200 HTML
  // page), the operator was bounced to sign-in, and the app-origin host-only
  // cookie could never authenticate the `/blog/api/*` calls it makes against
  // tortoise.*. The console's decided home is the session origin (`SCOPE.md`
  // §1.5, §3), so it is served there now and this is a SINGLE-HOP redirect to
  // app.premiselabs.co/admin — never a chained one (`SCOPE.md` §4 W2 / F12).
  // `/blog/api/*` is deliberately untouched: it does not match `/admin` and must
  // keep reaching this project (see the blog rule above — a redirect would drop
  // a POST body). Hash routes (`#/edit/:id`) are carried by the user agent
  // across the redirect, so deep links survive.
  //
  // 302, NOT 301 — RESOLVED in #4409. This branch was added under a rule that
  // already existed: §12 of the auth decision record (`premise-labs`
  // `engineering/auth/SCOPE.md`) reads “302, never a new 301”, with no “chained”
  // qualifier, and §1's in-scope list names `/admin` among the surfaces moving
  // to `app.*`. This rule therefore fixes the status of a NEW branch, and the
  // OVERRIDES marker on #3501/#3521 states it plainly ("New branches: 302").
  // The shipped 301 read W2's “never a chained new 301” as forbidding only
  // *chained* 301s; that reading does not survive §12's plain text. The marker
  // post-dates this branch, so the misreading was genuinely available at the
  // time — it is recorded here because the next lane should not re-make it.
  // The rationale applies in full here: `/admin` is an authenticated operator
  // surface with no SEO stake, so a permanent signal buys nothing and the
  // irreversibility is paid for nothing.
  if (
    url.pathname === "/admin" ||
    url.pathname === "/admin/" ||
    url.pathname.startsWith("/admin/")
  ) {
    return new Response(null, {
      status: 302,
      headers: { Location: APP_ORIGIN + "/admin" + url.search, ...HSTS },
    });
  }

  // ── Backstop for the same refusal (the primary guard is above the host block) ──
  // The primary guard refused every non-exempt path before any branch ran, so a
  // code reaches HERE only on an exempt surface that did NOT return above — today
  // that is an `APP_ONLY` page on a host the consolidation block does not handle
  // (`/signup?code=…` on the tortoise host, which `_redirects` sends to the app's
  // sign-up page and which cannot redeem a code either). Keeping the check here
  // means a future branch added above it cannot silently turn the refusal into a
  // render: the property "no page of this project renders around a stray code"
  // does not depend on the ordering being re-derived.
  if (isStrayAuthorizationCode(url)) {
    return strayReturnRefusal();
  }

  // ── The product host is now a PERMANENT 301 (epic #11762) ──────────────
  // This runs AFTER the host-independent app-origin branches above, so a
  // pinned `/auth`, `/auth/*` or `/admin` decision is never pre-empted by the
  // host move. Only surfaces that MOVED are redirected: static assets (css/js/
  // images) are not indexed pages and are shared by both hosts, so a blanket
  // redirect would break in-flight asset requests for no SEO gain, and an
  // unknown path keeps the 404 it has today rather than becoming a redirect
  // onto a 404.
  if (hostKey === "tortoise.premiselabs.co") {
    const toCompany = (target: string) =>
      new Response(null, {
        status: 301,
        headers: { Location: COMPANY_ORIGIN + target + url.search, ...HSTS },
      });

    if (isBlogPath) return toCompany(path);
    // The root IS the product page on this host today, so it maps to the one
    // canonical product URL; the raw duplicates map there too (`/index.html` is
    // a duplicate of the PRODUCT root on THIS host — it is the company page's
    // duplicate on the company host, which `_redirects` owns).
    if (path === "/" || path === "/index.html" || PRODUCT_ROOT.has(path)) {
      return toCompany(PRODUCT_PREFIX);
    }
    if (path === PRODUCT_PREFIX || path.startsWith(PRODUCT_PREFIX + "/")) {
      // Normalise HERE, not only on the company host: forwarding the raw path
      // would make every non-canonical spelling a SECOND hop
      // (`/tortoise/docs.html` → `…/tortoise/docs.html` → `…/tortoise/docs`) and
      // would turn an unknown one into a 301 onto a 404 — the two things this
      // block's own comment above says it must not do.
      const rest = productRest(path);
      if (rest !== "" && !PRODUCT_PAGES.has(`/${rest}`)) {
        return new Response("Not Found", { status: 404, headers: HSTS });
      }
      return toCompany(productCanonical(rest));
    }
    // The legacy alias lands on an app-origin page; one hop, never under the
    // product prefix (see SIGNIN_ALIAS above).
    if (SIGNIN_ALIAS.has(path)) {
      return new Response(null, {
        status: 301,
        headers: { Location: APP_ORIGIN + "/auth" + url.search, ...HSTS },
      });
    }
    // RETIRED page (#9486): the FIRST Location must name the canonical host, so
    // it redirects to the company host's target directly — one hop, and the
    // terminal URL is the 200 the retired route consolidates onto.
    if (RETIRED_PRIVACY_ALIAS.has(path)) return toCompany("/privacy");
    // Legal governs the business, so it lands at the company ROOT, not under
    // the product prefix.
    if (LEGAL_AT_ROOT.has(path)) return toCompany(path.replace(/\.html$/, ""));
    if (PRODUCT_PAGES.has(path)) return toCompany(PRODUCT_PREFIX + path.replace(/\.html$/, ""));
  }

  // ── The product page and product set are SERVED at premiselabs.co/tortoise ──
  // ONE host, one URL per page: the assets keep their filenames
  // (website/product.html, website/docs.html, …) and this rewrite is what makes
  // the new URLs resolve, so every 301 above lands on a 200 in the SAME deploy.
  // That property is what makes the map safe to ship before the file move — a
  // 301 onto a 404 would be an outage, and a 301 is browser-persistent.
  //
  // Host-independent on purpose (company host, *.pages.dev previews and local
  // dev alike), so the legal E2E suite can exercise the product URL against a
  // dev server without a production DNS preflight.
  if (url.pathname === PRODUCT_PREFIX || url.pathname.startsWith(PRODUCT_PREFIX + "/")) {
    const rest = productRest(url.pathname);
    // ⛔ ONLY the product set is servable under the prefix. Without this gate the
    // rewrite would serve ANY top-level page at a product URL — `/tortoise/index`
    // would answer the COMPANY homepage and `/tortoise/product` would be a second
    // URL for the product page, both 200. That is the duplicate-canonical
    // condition this whole change exists to remove.
    if (rest !== "" && !PRODUCT_PAGES.has(`/${rest}`)) {
      // ⛔ 404, NOT `context.next()`. Falling through would let Pages' pretty-URL
      // resolution answer `/tortoise/product` with product.html and
      // `/tortoise/index` with the company homepage — two more 200 duplicates of
      // pages that already have a canonical URL. Nothing lived under this prefix
      // before #11762, so a strict contract here breaks no existing URL.
      return new Response("Not Found", { status: 404, headers: HSTS });
    }
    // ⛔ ONE URL PER PAGE, INSIDE the prefix too.
    // `rest` strips `.html`, leading and trailing slashes, so without this,
    // `/tortoise/docs.html`, `/tortoise/docs/` and `/tortoise//docs` would all
    // answer 200 alongside `/tortoise/docs` — four indexable copies of one page,
    // which is the duplicate-canonical condition this change exists to remove, at
    // the URLs the change CREATES. `_redirects` cannot fix it: this rewrite returns
    // before the static rules run (measured — `/docs/` on the company host is a
    // single middleware hop today). A 301 onto the canonical form is safe because
    // no row of the map targets a `.html` or trailing-slash URL, and
    // `/tortoise/<page>` is a 200 in this same deploy.
    const canonical = productCanonical(rest);
    if (url.pathname !== canonical) {
      return new Response(null, {
        status: 301,
        headers: { Location: url.origin + canonical + url.search, ...HSTS },
      });
    }
    // ⛔ FETCH THE EXTENSIONLESS PATH, never `<rest>.html`.
    // `env.ASSETS.fetch` RE-ENTERS the asset router, where `_redirects` DOES
    // apply (measured — `MEMORY.md` `[deploy]`; the admin gate treats a 3xx from
    // `ASSETS.fetch` as "not an asset" for the same reason). `website/_redirects`
    // 301s `/docs.html`, `/faq.html`, `/self-hosted.html`,
    // `/design-partners-intro.html` and `/investors.html` to their extensionless
    // form, so fetching the `.html` spelling answers a 3xx, `res.ok` is false, and
    // five of the seven product rows would answer 404 — i.e. the 301 map would
    // point five permanent redirects at a 404. The extensionless path is not a
    // `_redirects` source and Pages resolves it to `<rest>.html` (that is how
    // `/docs` is served today).
    // `/product.html` is kept for the root row: it is the path the previous root
    // rewrite fetched in production and `_redirects` has no rule for it.
    const asset = rest === "" ? "/product.html" : `/${rest}`;
    const res = await context.env.ASSETS.fetch(url.origin + asset);
    if (res.ok) {
      return new Response(res.body, {
        status: 200,
        headers: {
          "Content-Type": "text/html; charset=utf-8",
          "Cache-Control": "public, max-age=60",
          "Content-Security-Policy": RELAXED_CSP,
          ...HSTS,
        },
      });
    }
    // No such product page: a 404 for the same reason as the gate above — never a
    // redirect onto a 404, and never a silent pass-through that could resolve to
    // some other document.
    return new Response("Not Found", { status: 404, headers: HSTS });
  }

  // Only rewrite the root path — everything else serves its own asset.
  if (url.pathname !== "/") {
    return context.next();
  }

  // premiselabs.co (and any other host) → company page (index.html)
  return context.next();
};
