#!/usr/bin/env node
// #4885: regenerate src/wizardRenderedCopy.snapshot.json.
//
//   cd website/apps/dashboard && node scripts/gen-wizard-rendered-copy-snapshot.mjs
//
// The snapshot is the RENDERED text of every agent-facing prose element that is
// written IN main.jsx — the class #4880's data-module snapshot could not see. It
// is committed so any change to that copy is a visible diff a reviewer must
// accept: an identical render passes, a deliberate or accidental divergence
// fails. Regenerating is part of the copy change, exactly as for
// `wizardPrompts.snapshot.json`.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import {
  WORLD,
  extractNodes,
  pinnable,
  renderNodes,
} from '../src/wizardRenderedCopy.js'

const here = dirname(fileURLToPath(import.meta.url))
const mainJsx = readFileSync(join(here, '..', 'src', 'main.jsx'), 'utf8')

const nodes = extractNodes(mainJsx)
const rendered = await renderNodes(mainJsx, nodes)

if (rendered.length === 0) {
  throw new Error('no prose nodes found in main.jsx — the extraction is broken, refusing to write an empty pin')
}

const snapshot = {
  _comment:
    'GENERATED by scripts/gen-wizard-rendered-copy-snapshot.mjs — do not hand-edit. '
    + 'The RENDERED text of every agent-facing prose element written in main.jsx (#4885). '
    + 'Changing it is a copy change and must be reviewed as one.',
  world: WORLD,
  nodes: rendered.map(pinnable),
}

const out = join(here, '..', 'src', 'wizardRenderedCopy.snapshot.json')
writeFileSync(out, `${JSON.stringify(snapshot, null, 2)}\n`)
const inline = rendered.filter((r) => r.kind === 'inline').length
console.log(`wrote ${out} (${rendered.length} nodes: ${inline} inline, `
  + `${rendered.reduce((n, r) => n + r.renders.length, 0)} rendered arms)`)
