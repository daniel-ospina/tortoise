#!/usr/bin/env node
// #4880 (carried by #4365): regenerate src/wizardPrompts.snapshot.json.
//
//   cd website/apps/dashboard && node scripts/gen-wizard-prompts-snapshot.mjs
//
// The snapshot is the RENDERED agent-facing copy the dashboard hands out. It is
// committed so that any change to that copy is a visible diff that a reviewer
// must accept — which is what makes the gate a gate: an identical render passes,
// a deliberate (or accidental) divergence fails.
//
// It exists because the guards used to read main.jsx as SOURCE TEXT. That
// mechanism cannot tell a reordered interpolation from a rendered reorder, and
// it produced five distinct false greens (#4365 review, cycle 11) — including a
// whole live prompt body that was never scanned at all.
//
// COVERAGE (#4820 review, cycle 9). This file is now the ONLY copy guard, so a
// LIVE surface that is absent from it can be changed with no failing test and no
// diff. Every agent-facing surface the dashboard renders is therefore pinned
// here, including the ones an earlier revision missed:
//   * BOTH key modes (`included` and `separate`) — main.jsx:2906 makes the mode a
//     live toggle (main.jsx:7349/7356/7371), so pinning only `included` left half
//     of what the wizard shows unguarded;
//   * HARNESS_INTRO / HARNESS_STEPS — rendered live (main.jsx:7365, :7833);
//   * HARNESS_CAPTURE_INSTALL — rendered live in the SETTINGS mount's collapsed
//     manual-install disclosure (`harnessStatusCard.jsx`). It is pinned because it
//     is still shipped copy a user can open; `main.jsx` has ZERO reads of it since
//     #3513 §2 moved the recipe out of the shared capture row, which now renders
//     `CAPTURE_INSTALL_POINTER` on every surface;
//   * PI_CAPTURE_INSTALL — the shared Pi recipe (`HARNESS_CAPTURE_INSTALL.pi`, and
//     the Pi leg of `HARNESS_INSTALL.pi`), pinned for the same reason.
// HARNESS_SKILLS is DELIBERATELY absent: its only consumers are inside
// LEGACY_WIZARD_ARCHIVED (main.jsx:7857/7864, flag=false), so pinning it would
// red the gate for an edit to dead code.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import {
  ONBOARDING_INSTRUCTIONS,
  WIZARD_CAPTIONS,
  wizardPromptText,
  wizardWorkflowsText,
} from '../src/wizardPrompts.js'
import {
  HARNESS_CAPTURE_INSTALL,
  HARNESS_INTRO,
  HARNESS_NAMES,
  HARNESS_STEPS,
  PI_CAPTURE_INSTALL,
  SKILLS_LIST,
  CODEX_DESKTOP_COMMAND,
} from '../src/harnesses.js'

// The harnesses with a live dashboard surface. `chatgpt` is deliberately absent:
// #2698 keeps it out of the chooser, so wizardPromptText returns '' for it and
// it has no wizard surface at all (its carrier is the setup docs page).
const HARNESSES = ['pi', 'cursor', 'claude', 'codex', 'claude-desktop', 'claude-web']
// Both are live: main.jsx:2906 `useState('included')`, passed to every prompt.
const MODES = ['included', 'separate']
const KEY = 'tk_snapshot' // deterministic: the renders must not depend on a real key

const prompts = {}
const promptsSeparate = {}
for (const harness of HARNESSES) {
  for (const step of [1, 2]) {
    const included = wizardPromptText(harness, step, KEY, 'included')
    if (included) prompts[`${harness}/${step}`] = included
    const separate = wizardPromptText(harness, step, KEY, 'separate')
    if (separate) promptsSeparate[`${harness}/${step}`] = separate
  }
}

// The ONE config-writing leaf still rendered as a single paste-able block
// (Codex Desktop — no terminal, #2827/#3232). The other harnesses are
// agent-driven, so their universal-command copy was deleted rather than
// pinned: pinning copy nobody renders is what let #3430's suite keep
// asserting a claim the product no longer makes. Pinned here so a change to
// it is a reviewed diff, and so the Python side can check the same string
// without parsing JavaScript source.
const commands = { codexDesktop: CODEX_DESKTOP_COMMAND(KEY) }

// The remaining live, data-driven surfaces.
const harnessIntro = HARNESS_INTRO
const harnessSteps = {}
for (const harness of Object.keys(HARNESS_NAMES)) {
  const steps = HARNESS_STEPS(harness, KEY)   // returns the step ARRAY (ends `})[harness]`)
  if (Array.isArray(steps)) harnessSteps[harness] = steps
}

const snapshot = {
  _comment:
    'GENERATED by scripts/gen-wizard-prompts-snapshot.mjs — do not hand-edit. '
    + 'This is the RENDERED agent-facing copy the dashboard hands out (#4365/#4880). '
    + 'Changing it is a copy change and must be reviewed as one.',
  skillSet: SKILLS_LIST,
  onboardingInstructions: ONBOARDING_INSTRUCTIONS,
  prompts,
  promptsSeparate,
  workflows: wizardWorkflowsText(KEY, 'included'),
  workflowsSeparate: wizardWorkflowsText(KEY, 'separate'),
  captions: WIZARD_CAPTIONS,
  commands,
  harnessIntro,
  harnessSteps,
  captureInstall: HARNESS_CAPTURE_INSTALL,
  piCaptureInstall: PI_CAPTURE_INSTALL,
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'wizardPrompts.snapshot.json')
writeFileSync(out, JSON.stringify(snapshot, null, 2) + '\n')
console.log(`wrote ${out} (${Object.keys(prompts).length} prompts × ${MODES.length} modes, `
  + `${Object.keys(commands).length} commands, ${Object.keys(harnessSteps).length} step sets)`)
