#!/usr/bin/env python
"""#14592 Phase D — make every artifact say, TRUTHFULLY, which code produced it.

Why this exists. The producers in this directory (`run_census.py`,
`run_readback.py`, `run_census2.py`, `run_census3.py`) each write a `provenance`
block naming themselves and their sha256. The four artifacts in `out/` were
carried from the 2026-11-25 run made BEFORE those producers were committed, so
none of them carries such a block — and `census.json` carries a key *named*
`provenance` that is really a `check_confidence(include_provenance=True)` CALL
RECEIPT. A reader could therefore not tell which code produced which number,
which is the whole value of the bundle.

Re-running the producers is not possible here: `xv14592_operating_model` lived in
this lane's private FalkorDB container, which was torn down at the end of the
run (the report's §9 states it). So this script MEASURES the gap rather than
papering over it — it writes a provenance block whose every field is computed
from the artifact and the producer's own source:

  * `artifact_status: "pre-producer"` and `produced_by_committed_producer: false`
    when the artifact does not carry a producer-written block;
  * `missing_producer_keys` — the keys the committed producer writes and this
    artifact does not have, read from that producer's own `WRITTEN_KEYS`;
  * `hardcoded_point_ids` — a `point_id`/`node_id` ARGUMENT whose value is a
    `pt_…` literal that appears nowhere in the producer's source (a script that
    discovers ids by content cannot have emitted one).

It REFUSES to overwrite a producer-written block: a real run's own provenance is
evidence, and a stamp that replaced it would be the same defect in reverse.

    python stamp_provenance.py            # write/refresh the blocks
    python stamp_provenance.py --check    # exit 1 if any block is missing/stale

`--check` recomputes every field from scratch, so a stale stamp (an artifact
regenerated by its producer while the old stamp lingers, or a deviation that has
since been fixed) reds instead of quietly surviving.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
WT = HERE.parents[2]

#: Every artifact in `out/` that is expected to describe its producing code.
ARTIFACTS = (
    ("census.json", "run_census.py"),
    ("census2.json", "run_census2.py"),
    ("census3.json", "run_census3.py"),
    ("readback.json", "run_readback.py"),
)

#: Keys a producer-written block carries. `probe_path`/`probe_sha256` are what
#: `_provenance()` writes; a stamped block deliberately has none of them, so the
#: two shapes cannot be confused in either direction.
PRODUCER_BLOCK_KEYS = ("probe_path", "probe_sha256", "graph")

#: A point id as the server mints it. Matched as a WHOLE value, so a truncated
#: `pt_f0a2b965…` in a docstring is not mistaken for the literal.
PT_ID = re.compile(r"^pt_[0-9a-f]{16,}$")

#: A `provenance` value that is really a tool call receipt — `census.json`
#: shipped one (`tortoise_check_confidence(include_provenance=True)`), which made
#: the artifact LOOK self-described while carrying no producer block at all. The
#: collision is renamed to this key, which is what the fixed `run_census.py`
#: writes too.
RECEIPT_KEY = "confidence_provenance_read"

_ID_ARGUMENTS = ("point_id", "node_id")


def _producer_source(name: str) -> str:
    return (HERE / name).read_text(encoding="utf-8")


def _written_keys(producer: str) -> tuple[str, ...]:
    """The keys the producer writes, read from the producer itself.

    Imported rather than duplicated: a copy here would drift the moment the
    producer gains a key, and the whole point is to measure the artifact against
    the code that claims to have made it. The modules are safe to import — every
    heavy import (`fastmcp`) lives inside `run()`.
    """
    path = HERE / producer
    spec = importlib.util.spec_from_file_location(f"_producer_{path.stem}", path)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    keys = getattr(module, "WRITTEN_KEYS", None)
    if not keys:
        raise SystemExit(f"{producer} declares no WRITTEN_KEYS — it cannot be graded")
    return tuple(keys)


def provenance_key_shape(doc: dict) -> str:
    """`producer-block` | `call-receipt` | `absent`, measured from the value."""
    block = doc.get("provenance")
    if block is None:
        return "absent"
    if isinstance(block, dict) and all(k in block for k in PRODUCER_BLOCK_KEYS):
        return "producer-block"
    return "call-receipt"


def point_id_arguments(doc: object, source: str) -> list[str]:
    """`pt_…` literals passed AS AN ARGUMENT that the producer never spells.

    Only call arguments are graded: a producer legitimately records an id it
    DISCOVERED as a result (`reversal_point_id`, an `expand` row's `related_id`).
    What it cannot legitimately do is ask the server about an id it was never
    given — that is the hardcoded id this bundle shipped.
    """
    found: list[str] = []

    def walk(node: object) -> None:
        if isinstance(node, dict):
            args = node.get("args")
            if isinstance(args, dict):
                for key in _ID_ARGUMENTS:
                    value = args.get(key)
                    if isinstance(value, str) and PT_ID.match(value) and value not in source:
                        found.append(value)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(doc)
    return sorted(set(found))


def _is_receipt(node: object) -> bool:
    """A `_call()` receipt — `{tool, args, ok, reply}` — not a provenance block."""
    return isinstance(node, dict) and {"tool", "args", "ok"} <= set(node)


def _pre_stamp(doc: dict) -> tuple[dict, str | None]:
    """The artifact as it was BEFORE any stamp, plus a rename to record.

    Without this the stamp grades itself: writing `provenance` turns the key
    shape from `absent` into something else and drops `provenance` out of the
    missing-key list, so every freshly stamped artifact would read as stale on
    the very next `--check`. Measured, which is why it is here.

    The receipt rename is undone for the measurement and re-applied on write, so
    `--check` is idempotent while the deviation stays recorded.
    """
    block = doc.get("provenance")
    if not (isinstance(block, dict) and block.get("stamp_probe")):
        if _is_receipt(block):
            return doc, f"provenance -> {RECEIPT_KEY}"
        return doc, None
    out = {k: v for k, v in doc.items() if k != "provenance"}
    renamed = block.get("renamed_receipt_key")
    if renamed and RECEIPT_KEY in out:
        out["provenance"] = out.pop(RECEIPT_KEY)
    return out, renamed


def expected_block(name: str, producer: str, doc: dict, source: str) -> dict | None:
    """The block this artifact must carry — or `None` when it needs no stamp.

    `None` means the artifact already carries its producer's own provenance; the
    stamp must then be ABSENT, and a lingering one is stale.
    """
    doc, renamed = _pre_stamp(doc)
    shape = provenance_key_shape(doc)
    if shape == "producer-block":
        return None
    missing = [k for k in _written_keys(producer) if k not in doc]
    hardcoded = point_id_arguments(doc, source)
    return {
        "artifact": name,
        "producer": producer,
        "producer_path": str((HERE / producer).relative_to(WT)),
        "artifact_status": "pre-producer",
        "produced_by_committed_producer": False,
        "provenance_key_shape": shape,
        "renamed_receipt_key": renamed,
        "missing_producer_keys": missing,
        "hardcoded_point_ids": hardcoded,
        "regenerate_with": (
            "TORTOISE_VENV=<checkout>/.venv TORTOISE_DB_URI=<uri to "
            "xv14592_operating_model> ./run.sh " + producer
        ),
        "note": (
            "Carried from the 2026-11-25 run, made before this producer was "
            "committed, so it is NOT this script's output. It cannot be "
            "regenerated: xv14592_operating_model lived in a lane container "
            "that was torn down (REPORT.md §9). The deviations above are "
            "measured by stamp_provenance.py, not asserted."
        ),
        "stamp_probe": "stamp_provenance.py",
    }


def _survey() -> list[tuple[str, dict, dict | None]]:
    rows = []
    for name, producer in ARTIFACTS:
        path = OUT / name
        if not path.exists():
            raise SystemExit(f"missing artifact: {path}")
        doc = json.loads(path.read_text(encoding="utf-8"))
        rows.append((name, doc, expected_block(name, producer, doc, _producer_source(producer))))
    return rows


def apply(check: bool) -> int:
    stale: list[str] = []
    for name, doc, want in _survey():
        have = doc.get("provenance")
        if have == want:
            continue
        stale.append(name)
        if check:
            print(f"STALE {name}: provenance block is "
                  f"{'missing' if have is None else 'out of date'}")
            continue
        if want is None:
            # A producer wrote its own block: the stamp has no business here.
            doc.pop("provenance", None)
        else:
            if want.get("renamed_receipt_key"):
                # Keep the receipt, under the name the fixed producer uses, so
                # renaming it does not silently DELETE a recorded call.
                doc[RECEIPT_KEY] = doc.get("provenance")
            doc["provenance"] = want
        (OUT / name).write_text(json.dumps(doc, indent=2, default=str) + "\n",
                                encoding="utf-8")
        print(f"stamped {name}")
    if check and stale:
        print(f"\n{len(stale)} artifact(s) need a stamp: run "
              "`python stamp_provenance.py` (no arguments) and commit the result")
        return 1
    return 0


if __name__ == "__main__":
    args = set(sys.argv[1:])
    unknown = args - {"--check"}
    if unknown:
        raise SystemExit(f"unknown argument(s): {' '.join(sorted(unknown))}")
    sys.exit(apply(check="--check" in args))
